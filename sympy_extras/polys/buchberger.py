from __future__ import annotations

from typing import Sequence, TypeVar

from .rings import Monomial, PolyElement, PolyRing, monomial_div, monomial_divides, monomial_lcm, monomial_mul

__all__ = ['buchberger', 's_polynomial']

T = TypeVar('T')

#: a critical pair: the indices of its two polynomials
Pair = tuple[int, int]


def _remainder(f: PolyElement[T], divisors: Sequence[PolyElement[T]]) -> PolyElement[T]:
    """The remainder of the division of ``f`` by ``divisors`` (in this
    order, over a field)."""
    ring = f.ring
    K = ring.domain
    key = ring.order.key
    leading: list[tuple[Monomial, T, list[tuple[Monomial, T]]]] = []
    for g in divisors:
        if g.terms:
            lm = max(g.terms, key=key)
            leading.append((lm, K.invert(g.terms[lm]), list(g.terms.items())))
    p = dict(f.terms)
    rest: dict[Monomial, T] = {}
    while p:
        m = max(p, key=key)
        c = p[m]
        for lm, inverse, terms in leading:
            if monomial_divides(lm, m):
                shift = monomial_div(m, lm)
                factor = K.mul(c, inverse)
                for gm, gc in terms:
                    t = monomial_mul(gm, shift)
                    old = p.get(t)
                    value = K.neg(K.mul(factor, gc)) if old is None else K.sub(old, K.mul(factor, gc))
                    if K.is_zero(value):
                        if old is not None:
                            del p[t]
                    else:
                        p[t] = value
                break
        else:
            rest[m] = c
            del p[m]
    return PolyElement(rest, ring)


# PORTED FROM SYMPY: sympy/polys/groebnertools.py:spoly
def s_polynomial(p1: PolyElement[T], p2: PolyElement[T]) -> PolyElement[T]:
    """``lcm/LM(p1)*p1 - lcm/LM(p2)*p2`` with ``lcm`` the lcm of the leading
    monomials: the S-polynomial of monic ``p1`` and ``p2``.

    >>> from sympy_extras.polys.domains import QQ
    >>> from sympy_extras.polys.rings import PolyRing, lex
    >>> from sympy_extras.polys.buchberger import s_polynomial
    >>> R = PolyRing(QQ, ['x', 'y'], lex)
    >>> x, y = R.gens
    >>> print(s_polynomial(x**2 - y, x*y - R.one))
    x - y**2
    """
    lcm = monomial_lcm(p1.LM, p2.LM)
    return p1.mul_monom(monomial_div(lcm, p1.LM)) - p2.mul_monom(monomial_div(lcm, p2.LM))


# PORTED FROM SYMPY: sympy/polys/groebnertools.py:_buchberger
def buchberger(polys: Sequence[PolyElement[T]], ring: PolyRing[T]) -> list[PolyElement[T]]:
    """The reduced Gröbner basis of the ideal generated by ``polys`` in
    ``ring`` (whose domain must be a field) for the order of the ring:
    monic, sorted by decreasing leading monomial.

    >>> from sympy_extras.polys.domains import QQ
    >>> from sympy_extras.polys.rings import PolyRing, lex
    >>> from sympy_extras.polys.buchberger import buchberger
    >>> R = PolyRing(QQ, ['x', 'y', 'z'], lex)
    >>> x, y, z = R.gens
    >>> third = QQ.from_int(1)/QQ.from_int(3)
    >>> F = [x**2 + y**2 + z**2 - R.one, x*y - z.mul_ground(third), x + y - z.mul_ground(QQ.from_int(2))]
    >>> [str(g) for g in buchberger(F, R)]
    ['x + y - 2*z', 'y**2 - 2*y*z + 1/3*z', 'z**2 - 2/15*z - 1/5']
    >>> buchberger([R.zero], R)
    []
    """
    if not ring.domain.is_field:
        raise ValueError("Buchberger's algorithm needs a field as the coefficient domain, got %s" % ring.domain)
    order = ring.order.key
    f: list[PolyElement[T]] = [p if p.ring == ring else PolyElement(dict(p.terms), ring) for p in polys if p.terms]
    if not f:
        return []

    def select(P: set[Pair]) -> Pair:
        # normal selection strategy: the pair with the smallest lcm
        return min(P, key=lambda pair: order(monomial_lcm(f[pair[0]].LM, f[pair[1]].LM)))

    index: dict[PolyElement[T], int] = {}

    def normal(g: PolyElement[T], J: Sequence[int]) -> int:
        """The index of the monic remainder of ``g`` by ``f[j]``, ``j`` in
        ``J``, appended to ``f`` if new; ``-1`` if it is zero."""
        h = _remainder(g, [f[j] for j in J])
        if not h.terms:
            return -1
        h = h.monic()
        found = index.get(h)
        if found is None:
            found = index[h] = len(f)
            f.append(h)
        return found

    def update(G: set[int], B: set[Pair], ih: int) -> tuple[set[int], set[Pair]]:
        # [BW] page 230: the new pairs (h, g), g in G, the old pairs, the basis
        mh = f[ih].LM
        C = set(G)
        D: set[Pair] = set()
        while C:
            ig = C.pop()
            mg = f[ig].LM
            LCMhg = monomial_lcm(mh, mg)

            def lcm_divides(ip: int) -> bool:
                # LCM(LM(h), LM(p)) divides LCM(LM(h), LM(g))
                return monomial_divides(monomial_lcm(mh, f[ip].LM), LCMhg)

            # HT(h) and HT(g) disjoint: mh*mg == LCMhg
            if monomial_mul(mh, mg) == LCMhg or (
                    not any(lcm_divides(ipx) for ipx in C) and not any(lcm_divides(pr[1]) for pr in D)):
                D.add((ih, ig))
        E: set[Pair] = set()
        while D:
            ih_, ig = D.pop()
            mg = f[ig].LM
            if monomial_mul(mh, mg) != monomial_lcm(mh, mg):
                E.add((ih_, ig))
        B_new: set[Pair] = set()
        while B:
            ig1, ig2 = B.pop()
            mg1 = f[ig1].LM
            mg2 = f[ig2].LM
            LCM12 = monomial_lcm(mg1, mg2)
            # HT(h) does not divide lcm(HT(g1), HT(g2))
            if not monomial_divides(mh, LCM12) or monomial_lcm(mg1, mh) == LCM12 or monomial_lcm(mg2, mh) == LCM12:
                B_new.add((ig1, ig2))
        B_new |= E
        G_new: set[int] = set()
        while G:
            ig = G.pop()
            if not monomial_divides(mh, f[ig].LM):
                G_new.add(ig)
        G_new.add(ih)
        return G_new, B_new

    # replace f with a reduced list of initial polynomials; see [BW] page 203
    f1 = list(f)
    while True:
        f = f1
        f1 = []
        for i in range(len(f)):
            r = _remainder(f[i], f[:i])
            if r.terms:
                f1.append(r.monic())
        if f == f1:
            break

    F: set[int] = set()
    G: set[int] = set()
    CP: set[Pair] = set()
    for i, h in enumerate(f):
        index[h] = i
        F.add(i)
    # algorithm GROEBNERNEWS2 in [BW] page 232
    while F:
        # the polynomial with the smallest leading monomial
        ih = min(F, key=lambda i: order(f[i].LM))
        F.remove(ih)
        G, CP = update(G, CP, ih)
    while CP:
        pair = select(CP)
        CP.remove(pair)
        s = s_polynomial(f[pair[0]], f[pair[1]])
        # ordering the divisors is on average more efficient [Cox] page 111
        G1 = sorted(G, key=lambda g: order(f[g].LM))
        ih = normal(s, G1)
        if ih >= 0:
            G, CP = update(G, CP, ih)
    # G is a Gröbner basis: reduce it
    reduced: set[int] = set()
    for ig in G:
        ih = normal(f[ig], sorted(G - {ig}))
        if ih >= 0:
            reduced.add(ih)
    return sorted((f[i] for i in reduced), key=lambda p: order(p.LM), reverse=True)
