r"""Reduced Gröbner bases by Buchberger's algorithm on the typed rings of
:mod:`sympy_extras.polys.rings`, over any field of
:mod:`sympy_extras.polys.domains`.

This is a typed port of SymPy's ``_buchberger``
(:mod:`sympy.polys.groebnertools`): the improved algorithm GROEBNERNEWS2 of
Becker and Weispfenning [1]_ with the criteria of Gebauer and Möller [2]_
and the normal selection strategy (the pair with the smallest lcm of
leading monomials first). It is the algorithm of
``settings.groebner_algorithm = 'buchberger'``; the default, F4
(:mod:`sympy_extras.polys.f4`), computes the same reduced basis.

Examples
========

>>> from sympy_extras.polys.domains import GF, QQ
>>> from sympy_extras.polys.rings import PolyRing, grevlex, lex
>>> from sympy_extras.polys.buchberger import buchberger
>>> R = PolyRing(QQ, ['x', 'y'], grevlex)
>>> x, y = R.gens
>>> [str(g) for g in buchberger([x**2 + y**2 - R.one, x*y - R.from_int(2)], R)]
['y**3 + 2*x - y', 'x**2 + y**2 - 1', 'x*y - 2']
>>> F = PolyRing(GF(7), ['x', 'y'], lex)
>>> X, Y = F.gens
>>> [str(g) for g in buchberger([X*X - Y, (Y*Y).mul_ground(3) - X], F)]
['x + 4*y**2', 'y**4 + 3*y']

References
==========

.. [1] T. Becker, V. Weispfenning, Gröbner Bases: A Computational Approach
       to Commutative Algebra, Springer, 1993, page 232.
.. [2] R. Gebauer, H. M. Möller, On an installation of Buchberger's
       algorithm, J. Symbolic Computation 6 (1988) 275-286.
"""
