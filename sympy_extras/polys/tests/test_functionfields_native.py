"""Tests of the native function fields
(:mod:`sympy_extras.polys.functionfields`) on the objects of the core:
Trager's integral bases against the literature and against an
independent maximality test by the native Puiseux expansions, the local
bases at infinity and the normalization against the valuations of the
branches at infinity, the arithmetic (no SymPy)."""
from __future__ import annotations

from fractions import Fraction
from math import ceil

from sympy_extras.core import Integer, Symbol, oo
from sympy_extras.core.expr import Expr
from sympy_extras.polys.domains import QQ
from sympy_extras.polys.functionfields import Element, FunctionField, function_field, integral_basis
from sympy_extras.polys.polytools import cancel
from sympy_extras.polys.puiseux import Curve, puiseux_expansions

x, y, a, b, Y = Symbol('x'), Symbol('y'), Symbol('a'), Symbol('b'), Symbol('Y')


def _curve_in_Y(E: FunctionField[Fraction]) -> Expr:
    """The monic curve of the integral generator, in ``Y``."""
    R = E.R
    total: Expr = Integer(0)
    for k, c in enumerate(E.F):
        total = total + R.to_expr(c.numer) * Y**(E.n - k)
    return total


def _numerator_and_denominator(E: FunctionField[Fraction], w: Element[Fraction]) -> tuple[Curve, Curve]:
    """``w`` as a polynomial in ``x`` and ``Y`` over a polynomial in ``x``."""
    R = E.R
    denominator = R.one
    for c in w.coefficients:
        denominator = R.lcm(denominator, c.denom)
    numerator: Curve = {}
    for i, c in enumerate(w.coefficients):
        if c.numer:
            p = R.exquo(R.mul(c.numer, denominator), c.denom)
            d = len(p) - 1
            numerator[i] = {d - k: [v] for k, v in enumerate(p) if v}
    d = len(denominator) - 1
    return numerator, {0: {d - k: [v] for k, v in enumerate(denominator) if v}}


def _is_maximal_at(E: FunctionField[Fraction], basis: list[Element[Fraction]], point: Fraction) -> bool:
    """Whether no element ``sum(c_i w_i)/(x - point)`` with rational
    ``c_i`` is integral: the order generated by ``basis`` is then maximal
    at the point (van Hoeij's criterion), checked through the Puiseux
    expansions above it."""
    branches = puiseux_expansions(_curve_in_Y(E), x, Y, Integer(point.numerator) / point.denominator, order=3)
    rows: list[list[Fraction]] = []
    for branch in branches:
        L = branch.field
        series = []
        for w in basis:
            numerator, denominator = _numerator_and_denominator(E, w)
            series.append(branch.evaluate(numerator) * branch.evaluate(denominator).inverse(8))
        for j in range(-8, branch.ramification):
            # the coefficient of t^j of sum_i c_i w_i must vanish for j < e
            for coordinate in range(L.degree):
                row: list[Fraction] = []
                for s_i in series:
                    value = list(reversed(s_i.coefficient(j)))
                    value += [Fraction(0)] * (L.degree - len(value))
                    row.append(value[coordinate])
                rows.append(row)
    return not QQ.nullspace(rows, E.n)


def _check_integral_basis(F: Expr, points: list[Fraction]) -> FunctionField[Fraction]:
    E = function_field(F, x, y, QQ)
    basis = E.integral_basis()
    assert len(basis) == E.n
    for w in basis:
        assert E.is_integral(w), (F, w)
    # the discriminant of the curve is the discriminant of the basis times
    # the square of the index
    power = [Element(E, [E.Kx.zero] * k + [E.Kx.one]) for k in range(E.n)]
    quotient = E.Kx.quo(E.discriminant(power), E.discriminant(basis))
    assert len(quotient.denom) == 1
    for point in points:
        assert _is_maximal_at(E, basis, point), (F, point)
    return E


def _same(found: list[Expr], expected: list[Expr]) -> bool:
    return len(found) == len(expected) and all(cancel(u - v) == 0 for u, v in zip(found, expected))


def test_bases_of_the_literature() -> None:
    # Kauers 2008, example 6
    assert integral_basis(y**3 - x**2 * (x + 1), x, y) == [1, y, y**2 / x]
    # Bronstein's tutorial, examples 1 and 2
    assert integral_basis(y**4 + (x**2 + x) * y - x**2, x, y) == [1, y, y**2, y**3 / x]
    # simple radical extensions, formula (11) of the tutorial: y^n = H with
    # H = H_1 H_2^2 ... gives y^(i-1)/prod H_j^floor((i-1) j/n)
    assert integral_basis(y**2 - x**3, x, y) == [1, y / x]
    assert _same(integral_basis(y**4 - x**2 * (x + 1)**3, x, y),
                 [Integer(1), y, y**2 / (x * (x + 1)), y**3 / (x * (x + 1)**2)])
    assert integral_basis(y**2 - x**8 - 1, x, y) == [1, y]
    assert _same(integral_basis(y**2 - (x**2 + 1)**2 * (x - 3), x, y), [Integer(1), y / (x**2 + 1)])


def test_bases_are_maximal_by_puiseux_expansions() -> None:
    zero, minus_one = Fraction(0), Fraction(-1)
    for F, points in [(y**3 - x**2 * (x + 1), [zero, minus_one]), (y**4 + (x**2 + x) * y - x**2, [zero, minus_one]),
                      (y**2 - x**3, [zero]), ((y**2 - x)**2 - x**3, [zero]),
                      (y**4 - x**2 * (x + 1)**3, [zero, minus_one]), (y**6 - x**2 * (x + 1)**3, [zero, minus_one])]:
        _check_integral_basis(F, points)


def test_curves_which_are_not_monic() -> None:
    assert integral_basis(x * y**2 - 1, x, y) == [1, x * y]
    E = _check_integral_basis((x + 1) * y**2 - x**3, [Fraction(0), Fraction(-1)])
    assert _same([w.as_expr() for w in E.integral_basis()], [Integer(1), (x + 1) * y / x])


def test_parameters_in_the_coefficients() -> None:
    assert integral_basis(y**2 - x**3 - a * x - b, x, y) == [1, y]
    assert _same(integral_basis(y**2 - (x - a)**2 * (x - b), x, y), [Integer(1), y / (x - a)])
    # SymPy's PolynomialRing.convert from its fraction field of constants
    # failed here: "Cannot convert 1/(3*a) ... from QQ(a) to QQ(a)(x)"
    assert integral_basis(y**3 - a * x**2, x, y) == [1, y, y**2 / x]


def test_arithmetic() -> None:
    E = function_field(y**3 - x**2 * (x + 1), x, y, QQ)
    u = E.element(y**2 / x)
    assert (u * E.element(y)).as_expr() == x**2 + x
    assert (u * u.inverse()).as_expr() == 1
    assert E.element(y).derivative() == E.element((3 * x**2 + 2 * x) / (3 * y**2))
    assert not E.element(y).trace().numer
    assert E.element(y**3).trace() == E.Kx.from_expr(3 * x**2 * (x + 1))
    assert E.is_integral(E.element(y)) and E.is_integral(u) and not E.is_integral(E.element(y / x))


def test_coordinates_follow_a_basis_which_changes() -> None:
    # the inverses of the bases were cached by the identity of the list:
    # a list changed in place (or a new list at the address of a freed one,
    # as in the loop of Trager's algorithm) got the inverse of the old one,
    # and coordinates([0, 1]) instead of [0, x]
    E = function_field(y**2 - x**3, x, y, QQ)
    basis = [E.one(), E.generator()]
    assert E.coordinates(E.generator(), basis) == [E.Kx.zero, E.Kx.one]
    basis[1] = E.generator().scaled(E.Kx.from_expr(1 / x))
    assert E.coordinates(E.generator(), basis) == [E.Kx.zero, E.Kx.from_expr(x)]


def _valuation_at_infinity(E: FunctionField[Fraction], w: Element[Fraction]) -> Fraction:
    numerator, denominator = _numerator_and_denominator(E, w)
    values: list[Fraction] = []
    for branch in puiseux_expansions(_curve_in_Y(E), x, Y, oo, order=6):
        s = branch.evaluate(numerator) * branch.evaluate(denominator).inverse(12)
        v = s.valuation()
        assert v is not None
        values.append(Fraction(v, branch.ramification))
    return min(values)


def test_local_bases_at_infinity_and_pole_orders() -> None:
    for F in [y**2 - x**3 - 1, y**3 - x**2 * (x + 1), y**4 + (x**2 + x) * y - x**2, y**4 - 4 * x * y**2 + 4,
              (x + 1) * y**2 - x**3, y**2 - x**8 - 1]:
        E = function_field(F, x, y, QQ)
        for w in E.local_basis_at_infinity():
            assert _valuation_at_infinity(E, w) >= 0, (F, w)
        for w in E.integral_basis():
            assert E.pole_order_at_infinity(w) == ceil(-_valuation_at_infinity(E, w)), (F, w)


def test_normal_bases() -> None:
    E = function_field(y**2 - x**3 - 1, x, y, QQ)
    assert [w.as_expr() for w in E.normal_basis()] == [1, y]
    assert E.pole_orders_at_infinity(E.normal_basis()) == [0, 2]
    for F in [y**3 - x**2 * (x + 1), y**4 + (x**2 + x) * y - x**2, y**4 - 4 * x * y**2 + 4, (x + 1) * y**2 - x**3]:
        E = function_field(F, x, y, QQ)
        normal = E.normal_basis()
        orders = E.pole_orders_at_infinity(normal)
        # the module is the integral closure still
        for w in normal:
            assert E.is_integral(w)
        integral = E.integral_basis()
        for w in normal:
            assert all(len(c.denom) == 1 for c in E.coordinates(w, integral))
        for w in integral:
            assert all(len(c.denom) == 1 for c in E.coordinates(w, normal))
        # normal: the pole order of a combination is the maximum of the terms
        combination = E.zero()
        for k, w in enumerate(normal):
            combination = combination + w.scaled(E.Kx.from_expr(x**(k + 1) + 1))
        assert E.pole_order_at_infinity(combination) == max(k + 1 + orders[k] for k in range(E.n))
        assert E.pole_order_at_infinity(combination) == ceil(-_valuation_at_infinity(E, combination))


def test_number_field_constants() -> None:
    # the curve y^2 = 2 x^2 + x^3 over QQ(sqrt(2)): the same basis, the
    # constants in the field
    K = puiseux_expansions(y**2 - 2 - x, x, y, Integer(0))[0].field
    E: FunctionField[list[Fraction]] = function_field(y**2 - 2 * x**2 - x**3, x, y, K)
    assert [w.as_expr() for w in E.integral_basis()] == [1, y / x]


def test_conversion_to_a_larger_field_of_constants() -> None:
    E = function_field(y**3 - x**2 * (x + 1), x, y, QQ)
    K = puiseux_expansions(y**2 - 2 - x, x, y, Integer(0))[0].field
    E_K: FunctionField[list[Fraction]] = function_field(y**3 - x**2 * (x + 1), x, y, K)
    w = E_K.convert(E.integral_basis()[2])
    assert w.as_expr() == y**2 / x and (w * w).as_expr() == E_K.element(y**4 / x**2).as_expr()
