r"""Algebraic function fields `K(x)[y]/(F)`: arithmetic, integral bases
by Trager's algorithm, local integral bases at infinity, and bases normal
at infinity.

Let `F \in K[x][y]` be monic in `y`, squarefree, of degree `n`; `E =
K(x)[y]/(F)` is an extension of degree `n` of `K(x)`. An element of `E`
is *integral* (over `K[x]`) when it is a root of a monic polynomial with
coefficients in `K[x]`; the integral elements form a free `K[x]`-module
of rank `n`, the *integral closure* `O`, whose bases are the *integral
bases* of `E`. They are the analogue of the polynomials among the
rational functions: an integral element has a value at every finite
point of every branch, and Trager's Hermite reduction for the integration
of algebraic functions needs the integrand's numerator written in one.

**Trager's algorithm** [Trager]_ (the Round 2 algorithm of Zassenhaus
and Ford in the function field case, with the trace radical of
[Abelard]_ section 3) enlarges the order `V = K[x]w_1 + \cdots + K[x]w_n`
generated by a basis of integral elements until it is the integral
closure:

1. the *discriminant* `\operatorname{disc}(V) = \det(\operatorname{Tr}(w_i
   w_j))` is a polynomial; `V` is maximal at the irreducible factors
   which divide it once, so let `Q` be the product of the factors
   dividing it twice or more (`\prod_{i \ge 2} f_i` for the squarefree
   factorization `\prod f_i^i`); `V = O` when `Q = 1`;
2. the `Q`-*trace radical* `J = \{u \in V : \operatorname{Tr}(u v) \equiv
   0 \pmod Q \text{ for all } v \in V\}` is the radical of `Q V` (in
   characteristic zero); its basis is the kernel over `K[x]` of `[T \mid
   -Q I]`, `T` the trace matrix;
3. the *idealizer* `\hat V = \{u \in E : u J \subseteq J\}` contains `V`;
   `V = O` exactly when `\hat V = V` (Trager, Theorem 1 and Corollary 2),
   and otherwise `\hat V` is a strictly larger order of integral
   elements, with which the loop continues. The idealizer is computed
   by linear algebra over `K[x]`: writing the condition `u \cdot M_k
   A^{-1} \in K[x]^n` for each basis element `j_k` of `J` (`M_k` the
   matrix of multiplication by `j_k`, `A` the matrix of the basis of
   `J`), a column echelon form `[H \mid 0]` of the stacked matrix gives
   `\hat V` as the row space of `\det(A)\, H^{-1}`.

The chain of orders is finite since the discriminant is divided by the
square of the index at every step. Everything happens in `K[x]` with
column echelon forms by the Euclidean algorithm (no number fields, and
the parameters of a field `K = \mathbb{Q}(a, b)` are allowed). The basis
returned is in Hermite normal form (monic pivots, the entries above them
reduced), which the module determines: the result does not depend on
the choices made along the way.

**At infinity.** The elements integral at infinity, `O_\infty`, are
those with no pole on any branch above `x = \infty`; a local basis of
them is the integral basis of the curve in `z = 1/x` (made monic by `Y
= z^m y`), and an integral basis `w` is *normal at infinity* [Trager]_
when `(x^{-k_i} w_i)`, `k_i` the pole order of `w_i` at infinity, is
such a local basis: then an element `\sum_i a_i w_i` with polynomial
`a_i` has pole order `\max_i (\deg a_i + k_i)` at infinity, the degrees
of the coordinates are bounded by the pole order allowed, which is what
the search of a function with a prescribed divisor and the test for a
nonelementary integral need. A basis is normalized by the leading forms:
when the matrix of `(x^{-k_i} w_i)` in the local basis is singular at
infinity, a kernel vector gives a combination `\sum_i c_i x^{k - k_i}
w_i` of smaller pole order, which replaces one of the `w_i` of pole
order `k`; the sum of the pole orders decreases and the process stops.

The module is native: it imports no SymPy. The field of constants `K` is
any typed field of characteristic zero (``QQ``, a number field
:class:`~sympy_extras.polys.domains.algebraicfield.AlgebraicField`, the
rational functions of the parameters
:class:`~sympy_extras.polys.domains.sparsefractionfield.SparseFractionField`),
so that :class:`FunctionField` is generic in the type of its constants;
:mod:`sympy_extras.polys.functionfields_sympy` is the face on SymPy's
domains, used by the integration on curves.

References
==========

.. [Trager] B. M. Trager, *Integration of algebraic functions*, PhD
   thesis, MIT, 1984, chapter 2 (integral bases, Theorem 1, Corollary
   2; normal at infinity).
.. [Abelard] S. Abelard, *On the complexity of computing integral bases
   of function fields*, CASC 2020, section 3 (the trace radical and the
   idealizer as polynomial linear algebra).
.. [Bronstein] M. Bronstein, *Symbolic integration tutorial*, ISSAC 1998,
   section 2 (integral elements, numerators and denominators).
"""
