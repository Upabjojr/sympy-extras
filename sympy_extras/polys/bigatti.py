r"""Bigatti's algorithm for the numerator of the Hilbert series of a
monomial ideal, on exponent tuples and integer coefficient lists (no
SymPy): the computation behind :mod:`sympy_extras.polys.hilbert` (and its
SymPy face :mod:`sympy_extras.polys.hilbert_sympy`) and the dimension and degree of
:class:`sympy_extras.polys.ideals.Ideal`.

The Hilbert series of $K[x_1, \ldots, x_n]/M$ for a monomial ideal $M$ is
$N(t)/(1 - t)^n$ with a polynomial numerator $N$. It satisfies, for a
monomial $m$ and an ideal $M'$,

$$N(M' + (m)) = N(M') - t^{\deg m} N(M' : m),$$

and Bigatti's algorithm applies it with a *pivot* $p = x_j^e$ which is not
a generator, chosen so that both $M + (p)$ and $M : p$ are much simpler
than $M$ ($x_j$ the variable occurring in the most generators, $e$ the
median of its exponents), and stops at the ideals whose numerator has a
formula: a product of ideals in disjoint sets of variables has the
product of the numerators, and an ideal generated by pure powers
$x_i^{a_i}$ and one more monomial $m$ has

$$N = \prod_i (1 - t^{a_i}) - t^{\deg m} \prod_i (1 - t^{a_i - m_i}).$$

Examples
========

>>> from sympy_extras.polys.bigatti import hilbert_numerator_coefficients
>>> hilbert_numerator_coefficients([(2, 0), (0, 2)])
[1, 0, -2, 0, 1]
>>> hilbert_numerator_coefficients([]), hilbert_numerator_coefficients([(0, 0)])
([1], [])

References
==========

.. [1] A. M. Bigatti, *Computation of Hilbert-Poincaré series*, Journal of
       Pure and Applied Algebra 119 (1997), 237-253.
.. [2] D. Cox, J. Little, D. O'Shea, *Ideals, Varieties, and Algorithms*,
       4th ed., Springer, 2015, Chapter 9 (the Hilbert function and the
       dimension).
"""
from __future__ import annotations

from typing import Iterable, Sequence

from .rings import Monomial

__all__ = ['hilbert_numerator_coefficients', 'minimal_generators', 'Series']

#: a polynomial in t with integer coefficients, dense, lowest degree first
Series = list[int]


def minimal_generators(monomials: Iterable[Sequence[int]]) -> list[Monomial]:
    """The minimal generators of the monomial ideal generated by the given
    exponent vectors, sorted by degree.

    Examples
    ========

    >>> from sympy_extras.polys.bigatti import minimal_generators
    >>> minimal_generators([(2, 1), (1, 0), (0, 3), (1, 3)])
    [(1, 0), (0, 3)]
    """
    minimal: list[Monomial] = []
    for m in sorted({tuple(m) for m in monomials}, key=lambda m: (sum(m), m)):
        if not any(_divides(u, m) for u in minimal):
            minimal.append(m)
    return minimal


def hilbert_numerator_coefficients(monomials: Iterable[Sequence[int]]) -> Series:
    r"""The coefficients of the numerator $N(t)$ of the Hilbert series
    $N(t)/(1 - t)^n$ of $K[x_1, \ldots, x_n]/M$, lowest degree first and
    without trailing zeros (``[]`` for the whole ring), for the monomial
    ideal $M$ generated by the given exponent vectors.

    >>> from sympy_extras.polys.bigatti import hilbert_numerator_coefficients
    >>> hilbert_numerator_coefficients([(1, 1, 0), (0, 1, 1)])
    [1, 0, -2, 1]
    """
    coefficients = _numerator(minimal_generators(monomials))
    while coefficients and not coefficients[-1]:
        coefficients.pop()
    return coefficients


def _divides(u: Monomial, m: Monomial) -> bool:
    return all(a <= b for a, b in zip(u, m))


def _multiply(f: Series, g: Series) -> Series:
    result = [0]*(len(f) + len(g) - 1)
    for i, a in enumerate(f):
        if a:
            for j, b in enumerate(g):
                result[i + j] += a*b
    return result


def _add_shifted(f: Series, g: Series, shift: int, sign: int) -> Series:
    """``f + sign * t**shift * g``."""
    result = f + [0]*max(0, shift + len(g) - len(f))
    for j, b in enumerate(g):
        result[shift + j] += sign*b
    return result


def _one_minus_power(a: int) -> Series:
    """``1 - t**a``."""
    result = [0]*(a + 1)
    result[0], result[a] = 1, -1
    return result


def _components(gens: list[Monomial]) -> list[list[Monomial]]:
    """The generators grouped by connected components of the graph whose
    vertices are the generators, two being adjacent when their supports
    meet: the ideal is the sum of the ideals of the components, in
    disjoint sets of variables."""
    n = len(gens[0])
    owner = list(range(len(gens)))

    def find(i: int) -> int:
        while owner[i] != i:
            owner[i] = owner[owner[i]]
            i = owner[i]
        return i

    for j in range(n):
        first = -1
        for i, m in enumerate(gens):
            if m[j]:
                if first < 0:
                    first = find(i)
                else:
                    owner[find(i)] = first
    groups: dict[int, list[Monomial]] = {}
    for i, m in enumerate(gens):
        groups.setdefault(find(i), []).append(m)
    return list(groups.values())


def _numerator(gens: list[Monomial]) -> Series:
    """Bigatti's recursion on a minimal generating set."""
    if not gens:
        return [1]
    if len(gens) == 1:
        if sum(gens[0]) == 0:
            return [0]
        return _one_minus_power(sum(gens[0]))
    components = _components(gens)
    if len(components) > 1:
        result = [1]
        for component in components:
            result = _multiply(result, _numerator(component))
        return result
    pure = [m for m in gens if sum(1 for e in m if e) == 1]
    if len(pure) >= len(gens) - 1:
        # pure powers x_i**a_i and at most one more monomial m:
        # prod (1 - t**a_i) - t**deg(m) prod (1 - t**(a_i - m_i))
        result = [1]
        others = [m for m in gens if sum(1 for e in m if e) > 1]
        if not others:
            # pure powers in the same variable cannot both be minimal, so
            # the generators are in disjoint variables: handled above
            raise AssertionError('pure powers in one component')
        [m] = others
        quotient = [1]
        for power in pure:
            j = max(range(len(power)), key=lambda i: power[i])
            result = _multiply(result, _one_minus_power(power[j]))
            quotient = _multiply(quotient, _one_minus_power(power[j] - m[j]))
        return _add_shifted(result, quotient, sum(m), -1)
    # the pivot x_j**e: x_j the variable in the most generators, e the
    # (lower) median of its exponents, which is less than the exponent of
    # a pure power of x_j among the generators
    n = len(gens[0])
    counts = [sum(1 for m in gens if m[j]) for j in range(n)]
    j = max(range(n), key=lambda i: counts[i])
    exponents = sorted(m[j] for m in gens if m[j])
    e = exponents[(len(exponents) - 1)//2]
    # M + (p): the generators not divisible by p, and p
    pivot = tuple(e if i == j else 0 for i in range(n))
    plus = [m for m in gens if m[j] < e] + [pivot]
    plus.sort(key=lambda m: (sum(m), m))
    # M : p = (m / gcd(m, p))
    quotient_gens = minimal_generators([tuple(max(a - e, 0) if i == j else a for i, a in enumerate(m)) for m in gens])
    # N(M + (p)) = N(M) - t**e N(M : p), solved for N(M)
    return _add_shifted(_numerator(plus), _numerator(quotient_gens), e, 1)
