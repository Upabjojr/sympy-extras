r"""The SymPy face of :mod:`sympy_extras.polys.hilbert`: Hilbert series of
monomial ideals by Bigatti's algorithm, the numerator a SymPy ``Poly`` and
the series a SymPy expression (the native module computes them).

The Hilbert series of $K[x_1, \ldots, x_n]/M$ for a monomial ideal $M$ is
$N(t)/(1 - t)^n$ with a polynomial numerator $N$, and the series of any
homogeneous ideal (or of the associated graded ring of any ideal) is that
of its leading term ideal for a graded order. The numerator satisfies, for
a monomial $m$ and an ideal $M'$,

$$N(M' + (m)) = N(M') - t^{\deg m} N(M' : m),$$

and the textbook recursion applies this to one generator at a time, which
is exponential in the number of generators. Bigatti's algorithm applies it
with a *pivot* $p = x_j^e$ which is not a generator, chosen so that both
$M + (p)$ and $M : p$ are much simpler than $M$ ($x_j$ the variable
occurring in the most generators, $e$ the median of its exponents), and
stops at the ideals whose numerator has a formula: a product of ideals in
disjoint sets of variables has the product of the numerators (so that
pure powers $x_i^{a_i}$ contribute the factors $1 - t^{a_i}$), and an
ideal generated by pure powers $x_i^{a_i}$ and one more monomial $m$ has

$$N = \prod_i (1 - t^{a_i}) - t^{\deg m} \prod_i (1 - t^{a_i - m_i}).$$

Examples
========

>>> from sympy.abc import t
>>> from sympy_extras.polys.hilbert_sympy import hilbert_numerator, hilbert_series
>>> hilbert_numerator([(2, 0), (0, 2)], t)
Poly(t**4 - 2*t**2 + 1, t, domain='ZZ')
>>> hilbert_series([(2, 0), (1, 1), (0, 2)], 2, t)
2*t + 1

References
==========

.. [1] A. M. Bigatti, *Computation of Hilbert-Poincaré series*, Journal of
       Pure and Applied Algebra 119 (1997), 237-253.
.. [2] D. Cox, J. Little, D. O'Shea, *Ideals, Varieties, and Algorithms*,
       4th ed., Springer, 2015, Chapter 9 (the Hilbert function and the
       dimension).
"""
from __future__ import annotations

from typing import Iterable, Sequence

from sympy.core.expr import Expr
from sympy.core.symbol import Symbol
from sympy.polys.polytools import Poly

from sympy_extras.core.symbol import Symbol as CoreSymbol

from . import hilbert as native
from .bigatti import minimal_generators

__all__ = ['hilbert_numerator', 'hilbert_series', 'minimal_generators']

def hilbert_numerator(monomials: Iterable[Sequence[int]], t: Symbol) -> Poly:
    r"""The numerator $N(t)$ of the Hilbert series $N(t)/(1 - t)^n$ of
    $K[x_1, \ldots, x_n]/M$ for the monomial ideal $M$ generated by the
    given exponent vectors, by Bigatti's algorithm.

    Examples
    ========

    >>> from sympy.abc import t
    >>> from sympy_extras.polys.hilbert_sympy import hilbert_numerator
    >>> hilbert_numerator([(2, 0), (0, 2)], t)
    Poly(t**4 - 2*t**2 + 1, t, domain='ZZ')
    >>> hilbert_numerator([(1, 1, 0), (0, 1, 1)], t)
    Poly(t**3 - 2*t**2 + 1, t, domain='ZZ')
    >>> hilbert_numerator([], t)
    Poly(1, t, domain='ZZ')
    """
    numerator = native.hilbert_numerator(monomials, CoreSymbol(t.name))
    return Poly(dict(numerator.terms()), t)


def hilbert_series(monomials: Iterable[Sequence[int]], variables: int, t: Symbol) -> Expr:
    r"""The Hilbert series of $K[x_1, \ldots, x_n]/M$ for the monomial
    ideal $M$ generated by the given exponent vectors, as a reduced
    rational function $q(t)/(1 - t)^d$ ($d$ the Krull dimension).

    Examples
    ========

    >>> from sympy.abc import t
    >>> from sympy_extras.polys.hilbert_sympy import hilbert_series
    >>> hilbert_series([(2, 0, 0), (1, 1, 0), (0, 2, 0)], 3, t)
    (2*t + 1)/(1 - t)
    >>> hilbert_series([(1, 0), (0, 1)], 2, t)
    1
    """
    q, exponent = native.reduced_hilbert_series(monomials, variables)
    numerator = Poly(dict(enumerate(q)), t).as_expr()
    if exponent == 0:
        return numerator
    return numerator/(1 - t)**exponent
