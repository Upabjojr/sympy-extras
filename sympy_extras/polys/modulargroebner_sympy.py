r"""The SymPy face of :mod:`sympy_extras.polys.modulargroebner`: the
modular Gröbner bases over the rationals on SymPy's ring elements
(:func:`sympy.polys.rings.ring`), with the results of the module before
its native port.

The polynomials over ``QQ``, ``ZZ`` and ``GF(p)`` are converted to the
typed rings of :mod:`sympy_extras.polys.rings` by
:mod:`sympy_extras.polys.interop` (the monomial order with the flattened
key of the SymPy order), the native functions compute, and the bases are
converted back. What stays on SymPy: the other coefficient domains
(algebraic fields, fields of rational functions) and the orders which are
not global, for which SymPy's ``groebner`` is called, as before.

Examples
========

>>> from sympy import QQ, ring, lex
>>> from sympy.polys.groebnertools import groebner
>>> from sympy_extras.polys.modulargroebner_sympy import modular_groebner
>>> R, x, y, z = ring("x,y,z", QQ, lex)
>>> F = [x**2 + y**2 + z**2 - 1, x*y - z/3, x + y - 2*z]
>>> G = modular_groebner(F, R)
>>> G
[x + y - 2*z, y**2 - 2*y*z + 1/3*z, z**2 - 2/15*z - 1/5]
>>> G == groebner(F, R)
True
"""
from __future__ import annotations

from typing import Iterable, Optional, Sequence

from sympy.polys.groebnertools import groebner as _groebner
from sympy.polys.orderings import MonomialOrder, grevlex, grlex
from sympy.polys.rings import PolyElement, PolyRing

from sympy_extras._timeout import attempt
from sympy_extras.settings import settings

from . import modulargroebner as native
from .interop import gf_from_sympy, gf_to_sympy, qq_from_sympy, qq_to_sympy, sympy_modulus, zz_from_sympy, zz_to_sympy
from .modulargroebner import (GRADED_FACTOR, GUARD_BITS, ModularTrace, chinese_remainder, default_primes,
                              rational_reconstruction)

__all__ = ['direct_groebner', 'groebner', 'modular_groebner', 'rational_reconstruction', 'chinese_remainder',
    'default_primes', 'ModularTrace', 'GRADED_FACTOR', 'GUARD_BITS']


def _applies(ring: PolyRing) -> bool:
    """Whether the modular algorithm applies: rational or integer
    coefficients and a global monomial order."""
    order = ring.order
    return bool(ring.domain.is_QQ or ring.domain.is_ZZ) and isinstance(order, MonomialOrder) \
        and order.is_global is True


def modular_groebner(polys: Sequence[PolyElement], ring: PolyRing, primes: Optional[Iterable[int]] = None,
                     trace: Optional[ModularTrace] = None) -> list[PolyElement]:
    """The reduced Gröbner basis of the ideal generated by ``polys`` in
    ``ring``, computed modulo primes and proven
    (:func:`sympy_extras.polys.modulargroebner.modular_groebner`); the
    result is the one of :func:`sympy.polys.groebnertools.groebner`.

    Parameters
    ==========

    polys : sequence of PolyElement
        The generators, elements of ``ring``.
    ring : PolyRing
        The ring, whose order is the order of the Gröbner basis. Over
        ``QQ`` the result is monic, over ``ZZ`` primitive with positive
        leading coefficients, sorted by decreasing leading monomials, as
        SymPy's is. For other domains (finite fields, algebraic fields,
        fields of fractions) and for orders which are not global SymPy's
        ``groebner`` is called.
    primes : iterable of int, optional
        The primes to use, in this order; the default primes if omitted.
        ``ValueError`` is raised if they run out.
    trace : ModularTrace, optional
        Filled in with the primes used, skipped and discarded.

    Examples
    ========

    >>> from sympy import QQ, ring, lex, primerange
    >>> from sympy_extras.polys.modulargroebner_sympy import modular_groebner, ModularTrace
    >>> R, x, y = ring("x,y", QQ, lex)
    >>> trace = ModularTrace()
    >>> modular_groebner([x**2 + y, x**2 + 7*y], R, primes=primerange(2, 100), trace=trace)
    [x**2, y]
    >>> trace.unlucky, trace.lucky
    ([2, 3], [5, 7])

    References
    ==========

    .. [1] E. A. Arnold, Modular algorithms for computing Gröbner bases,
           J. Symbolic Computation 35 (2003) 403-419.
    """
    if not _applies(ring):
        return list(_groebner(list(polys), ring))
    nonzero = [f for f in polys if f]
    if ring.domain.is_ZZ:
        typed_zz, polys_zz = zz_from_sympy(nonzero, ring)
        return zz_to_sympy(native.modular_groebner(polys_zz, typed_zz, primes, trace), ring)
    typed_qq, polys_qq = qq_from_sympy(nonzero, ring)
    return qq_to_sympy(native.modular_groebner(polys_qq, typed_qq, primes, trace), ring)


def direct_groebner(polys: Sequence[PolyElement], ring: PolyRing) -> list[PolyElement]:
    """The reduced Gröbner basis by the direct computation of
    ``settings.groebner_algorithm`` over ``QQ`` and ``GF(p)``: the typed F4
    or Buchberger algorithm
    (:func:`sympy_extras.polys.modulargroebner.direct_groebner`), SymPy's
    ``groebner`` over the other domains.

    Examples
    ========

    >>> from sympy import QQ, ring, grevlex
    >>> from sympy_extras.polys.modulargroebner_sympy import direct_groebner
    >>> R, x, y = ring("x,y", QQ, grevlex)
    >>> direct_groebner([x**2 + y**2 - 1, x*y - 2], R)
    [y**3 + 2*x - y, x**2 + y**2 - 1, x*y - 2]
    """
    nonzero = [f for f in polys if f]
    if ring.domain.is_QQ:
        typed_qq, polys_qq = qq_from_sympy(nonzero, ring)
        return qq_to_sympy(native.direct_groebner(polys_qq, typed_qq), ring)
    p = sympy_modulus(ring)
    if p is not None:
        typed_gf, polys_gf = gf_from_sympy(nonzero, ring, p)
        return gf_to_sympy(native.direct_groebner(polys_gf, typed_gf), ring)
    return list(_groebner(nonzero, ring))


def groebner(polys: Sequence[PolyElement], ring: PolyRing) -> list[PolyElement]:
    """The reduced Gröbner basis of ``polys`` in ``ring``, by the direct
    computation (:func:`direct_groebner`) or by :func:`modular_groebner`,
    whichever is expected to be faster
    (:func:`sympy_extras.polys.modulargroebner.groebner`, whose
    documentation gives the time limits and the reasons). Over ``ZZ``
    SymPy's ``groebner`` is given the time of the direct computation;
    with ``settings.modular_groebner`` off and over the other domains only
    the direct computation is used.

    Examples
    ========

    >>> from sympy import QQ, ring, grevlex
    >>> from sympy_extras.polys.modulargroebner_sympy import groebner
    >>> from sympy_extras.settings import configure
    >>> R, x, y = ring("x,y", QQ, grevlex)
    >>> groebner([x**2 + y**2 - 1, x*y - 2], R)
    [y**3 + 2*x - y, x**2 + y**2 - 1, x*y - 2]
    >>> with configure(groebner_direct_time=0):
    ...     groebner([x**2 + y**2 - 1, x*y - 2], R)
    [y**3 + 2*x - y, x**2 + y**2 - 1, x*y - 2]
    """
    nonzero = [f for f in polys if f]
    if not settings.modular_groebner or not _applies(ring):
        return direct_groebner(nonzero, ring)
    if ring.domain.is_QQ:
        typed_qq, polys_qq = qq_from_sympy(nonzero, ring)
        return qq_to_sympy(native.groebner(polys_qq, typed_qq), ring)
    seconds = settings.groebner_direct_time
    if ring.order in (grevlex, grlex):
        seconds *= GRADED_FACTOR
    if seconds > 0:
        direct = attempt(lambda: direct_groebner(list(nonzero), ring), seconds)
        if direct is not None:
            return direct
    return modular_groebner(nonzero, ring)
