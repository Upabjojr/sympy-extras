r"""Hilbert series of monomial ideals by Bigatti's algorithm, on the typed
polynomial layer (no SymPy): the numerator a :class:`DensePoly` over
``ZZ``, the series a core expression.

The Hilbert series of $K[x_1, \ldots, x_n]/M$ for a monomial ideal $M$ is
$N(t)/(1 - t)^n$ with a polynomial numerator $N$, and the series of any
homogeneous ideal (or of the associated graded ring of any ideal) is that
of its leading term ideal for a graded order. The numerator satisfies, for
a monomial $m$ and an ideal $M'$,

$$N(M' + (m)) = N(M') - t^{\deg m} N(M' : m),$$

and the textbook recursion applies this to one generator at a time, which
is exponential in the number of generators. Bigatti's algorithm applies it
with a *pivot* $p = x_j^e$ which is not a generator, chosen so that both
$M + (p)$ and $M : p$ are much simpler than $M$ ($x_j$ the variable
occurring in the most generators, $e$ the median of its exponents), and
stops at the ideals whose numerator has a formula: a product of ideals in
disjoint sets of variables has the product of the numerators (so that
pure powers $x_i^{a_i}$ contribute the factors $1 - t^{a_i}$), and an
ideal generated by pure powers $x_i^{a_i}$ and one more monomial $m$ has

$$N = \prod_i (1 - t^{a_i}) - t^{\deg m} \prod_i (1 - t^{a_i - m_i}).$$

The computation is that of :mod:`sympy_extras.polys.bigatti` (exponent
tuples and integer lists); :mod:`sympy_extras.polys.hilbert_sympy` is the
SymPy face of this module (a SymPy ``Poly`` and a SymPy expression).

Examples
========

>>> from sympy_extras.core import Symbol
>>> from sympy_extras.polys.hilbert import hilbert_numerator, hilbert_series
>>> t = Symbol('t')
>>> hilbert_numerator([(2, 0), (0, 2)], t)
DensePoly([1, 0, -2, 0, 1], ZZ, t)
>>> hilbert_series([(2, 0), (1, 1), (0, 2)], 2, t)
2*t + 1

References
==========

.. [1] A. M. Bigatti, *Computation of Hilbert-Poincaré series*, Journal of
       Pure and Applied Algebra 119 (1997), 237-253.
.. [2] D. Cox, J. Little, D. O'Shea, *Ideals, Varieties, and Algorithms*,
       4th ed., Springer, 2015, Chapter 9 (the Hilbert function and the
       dimension).
"""
from __future__ import annotations

from typing import Iterable, Sequence

from sympy_extras.core.add import add
from sympy_extras.core.expr import Expr
from sympy_extras.core.mul import mul
from sympy_extras.core.numbers import Integer
from sympy_extras.core.power import pow
from sympy_extras.core.symbol import Symbol

from .bigatti import Series, hilbert_numerator_coefficients, minimal_generators
from .domains.integerring import ZZ
from .polyclasses import DensePoly

__all__ = ['hilbert_numerator', 'hilbert_series', 'reduced_hilbert_series', 'minimal_generators']


def hilbert_numerator(monomials: Iterable[Sequence[int]], t: Symbol) -> DensePoly[int]:
    r"""The numerator $N(t)$ of the Hilbert series $N(t)/(1 - t)^n$ of
    $K[x_1, \ldots, x_n]/M$ for the monomial ideal $M$ generated by the
    given exponent vectors, by Bigatti's algorithm.

    Examples
    ========

    >>> from sympy_extras.core import Symbol
    >>> from sympy_extras.polys.hilbert import hilbert_numerator
    >>> t = Symbol('t')
    >>> hilbert_numerator([(2, 0), (0, 2)], t).to_expr()
    t**4 - 2*t**2 + 1
    >>> hilbert_numerator([(1, 1, 0), (0, 1, 1)], t).to_expr()
    t**3 - 2*t**2 + 1
    >>> hilbert_numerator([], t).to_expr(), hilbert_numerator([(0, 0)], t).is_zero
    (1, True)
    """
    coefficients: Series = hilbert_numerator_coefficients(monomials)
    return DensePoly(list(reversed(coefficients)), ZZ, t)


def reduced_hilbert_series(monomials: Iterable[Sequence[int]], variables: int) -> tuple[Series, int]:
    r"""``(q, d)`` with $q$ the numerator of the Hilbert series of
    $K[x_1, \ldots, x_n]/M$ (``n = variables``) divided by the largest
    power of $1 - t$ which divides it and below $(1 - t)^n$ (coefficients
    lowest degree first, ``[]`` when $M$ is the whole ring), and ``d`` the
    remaining exponent of $1 - t$ (the Krull dimension, ``variables`` for
    the whole ring).

    >>> from sympy_extras.polys.hilbert import reduced_hilbert_series
    >>> reduced_hilbert_series([(2, 0, 0), (1, 1, 0), (0, 2, 0)], 3)
    ([1, 2], 1)
    >>> reduced_hilbert_series([(0, 0)], 2)
    ([], 2)
    """
    numerator = hilbert_numerator_coefficients(monomials)
    exponent = variables
    while exponent > 0 and numerator and sum(numerator) == 0:
        # N = (1 - t) q: q_i = N_0 + ... + N_i
        quotient: Series = []
        running = 0
        for c in numerator[:-1]:
            running += c
            quotient.append(running)
        numerator, exponent = quotient, exponent - 1
    while numerator and numerator[-1] == 0:
        numerator.pop()
    return numerator, exponent


def hilbert_series(monomials: Iterable[Sequence[int]], variables: int, t: Symbol) -> Expr:
    r"""The Hilbert series of $K[x_1, \ldots, x_n]/M$ for the monomial
    ideal $M$ generated by the given exponent vectors, as a reduced
    rational function $q(t)/(1 - t)^d$ ($d$ the Krull dimension).

    Examples
    ========

    >>> from sympy_extras.core import Symbol
    >>> from sympy_extras.polys.hilbert import hilbert_series
    >>> t = Symbol('t')
    >>> hilbert_series([(2, 0, 0), (1, 1, 0), (0, 2, 0)], 3, t)
    (2*t + 1)/(1 - t)
    >>> hilbert_series([(1, 0), (0, 1)], 2, t), hilbert_series([], 2, t)
    (1, (1 - t)**(-2))
    """
    q, exponent = reduced_hilbert_series(monomials, variables)
    if not q:
        return Integer(0)
    numerator = DensePoly(list(reversed(q)), ZZ, t).to_expr()
    if exponent == 0:
        return numerator
    return mul(numerator, pow(add(Integer(1), mul(Integer(-1), t)), Integer(-exponent)))
