def independent_set(ideal: Ideal[T]) -> list[Symbol]:
    r"""A maximal independent set of variables modulo a proper ideal: a set
    `u` of variables, as many as the dimension, with `I \cap K[u] = 0`.

    No leading monomial of a Gröbner basis lies in `K[u]`
    [KredelWeispfenning]_; the first such subset of the variables, in the
    order of the combinations, is returned.

    Examples
    ========

    >>> from sympy_extras.core import symbols
    >>> from sympy_extras.polys.domains import QQ
    >>> from sympy_extras.polys.ideals import Ideal
    >>> from sympy_extras.polys.idealdecomposition import independent_set
    >>> x, y, z = symbols('x y z')
    >>> independent_set(Ideal([x*y, x*z], x, y, z, domain=QQ))
    [y, z]
    >>> independent_set(Ideal([x**2 - y, z], x, y, z, domain=QQ))
    [y]
    """
    if ideal.is_whole_ring():
        raise ValueError("the whole ring has no independent set")
    leading: list[Monomial] = ideal.leading_monomials(grevlex)
    n = len(ideal.symbols)
    for subset in combinations(range(n), ideal.dimension()):
        chosen = set(subset)
        if all(any(e and i not in chosen for i, e in enumerate(m)) for m in leading):
            return [ideal.symbols[i] for i in subset]
    raise RuntimeError("no independent set of the size of the dimension")


def _contraction(ideal: Ideal[T], free: list[Symbol]) -> tuple[Ideal[T], Expr]:
    r"""The contraction `I K(u)[x] \cap K[x]` of the extension of the ideal
    to the field of rational functions in the independent variables `u`,
    and the polynomial `h` of `K[u]` with contraction `I : h^\infty`.

    The reduced Gröbner basis of `I` for a block order with `x > u` is a
    Gröbner basis of the extension, and the contraction is the saturation
    by the product of the leading coefficients of its elements as
    polynomials in `x` ([GTZ]_, [BeckerWeispfenning]_ chapter 8): here by
    the squarefree part of their least common multiple."""
    main = [i for i, s in enumerate(ideal.symbols) if s not in free]
    if not free or not main:
        return ideal, Integer(1)
    positions = main + [ideal.symbols.index(s) for s in free]
    k = len(main)
    K = ideal.domain
    names = ['v%d' % i for i in range(len(positions))]
    R: PolyRing[T] = PolyRing(K, names, elimination_order(k, len(positions), grevlex))
    gens = [PolyElement({tuple(m[i] for i in positions): c for m, c in g.terms.items()}, R) for g in ideal.gens]
    basis = groebner(gens, R)
    h = Poly(Integer(1), *free)
    for g in basis:
        top = g.LM[:k]
        terms: list[Expr] = []
        for m, c in g.terms.items():
            if m[:k] == top:
                factors: list[Expr] = [K.to_expr(c)]
                factors.extend(pow(v, Integer(e)) for v, e in zip(free, m[k:]) if e)
                terms.append(mul(*factors))
        h = h.lcm(Poly(add(*terms), *free))
    # the squarefree part
    _, parts = h.sqf_list()
    if not parts:
        return ideal, Integer(1)
    factor = mul(*[p.as_expr() for p, _ in parts])
    return ideal.saturate(factor).reduced(), factor


def _separator(prime: Ideal[T], others: list[Ideal[T]]) -> Expr:
    """A polynomial in every one of the ``others`` and not in ``prime``
    (none of which contains ``prime``): the product of a generator of each
    which is not in ``prime``, the one of least degree."""
    factors: list[Expr] = []
    for other in others:
        outside = [g for g in other.groebner_basis() if not prime.contains(g)]
        if not outside:
            raise RuntimeError("a prime contains another one of the same dimension")
        chosen = min(outside, key=lambda g: (max(sum(m) for m in g.terms), len(g.terms)))
        factors.append(other.to_expr(chosen))
    return mul(*factors)


def _zero_dimensional_components(ideal: Ideal[T]) -> list[PrimaryComponent[T]]:
    r"""The primary components of an ideal of dimension zero [GTZ]_: for a
    linear form `\ell` which takes different values at the zeros, with
    minimal polynomial `\prod_j p_j^{k_j}` modulo the ideal, they are
    `I + (p_j(\ell)^{k_j})`, of primes `\sqrt{I} + (p_j(\ell))` (by the
    Chinese remainder theorem, `p_j(\ell)` is nilpotent modulo the
    component of the zeros of `p_j` and a unit modulo the others). All
    by linear algebra in `K[x]/I`, where saturations by separators need
    eliminations (minutes for four points with coefficients of ten
    digits)."""
    root = ideal.radical()
    points = root.vector_space_dimension()
    y: Symbol = Dummy('y')
    for form in separating_forms(ideal.symbols, points):
        minimal = ideal.minimal_polynomial(form, y)
        if minimal.sqf_part().degree < points:
            continue
        components: list[PrimaryComponent[T]] = []
        for factor, k in minimal.factor_list()[1]:
            value = as_expr(factor.to_expr().xreplace({y: form}))
            power = _like(ideal, [pow(value, Integer(k))])
            prime = _like(ideal, [value])
            components.append(((ideal + power).reduced(), (root + prime).reduced()))
        return components
    raise RuntimeError("no separating linear form was found")


def _top_components(ideal: Ideal[T]) -> tuple[list[PrimaryComponent[T]], Ideal[T], Expr]:
    """The primary components of ``ideal`` of greatest dimension whose
    primes do not meet `K[u]`, for the independent set `u` of
    :func:`independent_set`, their intersection (the contraction) and the
    polynomial `h` with contraction `I : h^\\infty`."""
    free = independent_set(ideal)
    if not free:
        return _zero_dimensional_components(ideal), ideal, Integer(1)
    contracted, h = _contraction(ideal, free)
    # the extension has dimension zero: every associated prime of the
    # contraction is minimal, of the dimension of the ideal
    primes = minimal_primes(contracted)
    if not primes or any(p.dimension() != len(free) for p in primes):
        raise RuntimeError("the contraction of the extension is not unmixed")
    if len(primes) == 1:
        return [(contracted, primes[0])], contracted, h
    components: list[PrimaryComponent[T]] = []
    for i, prime in enumerate(primes):
        separator = _separator(prime, primes[:i] + primes[i + 1:])
        components.append((contracted.saturate(separator).reduced(), prime))
    return components, contracted, h


def _saturation_exponent(ideal: Ideal[T], saturated: Ideal[T], h: Expr) -> int:
    """The least `m` with `I : h^m = I : h^\\infty` (``saturated``): the
    least `m` with `h^m g` in `I` for every generator `g` of the
    saturation, found by normal forms modulo `I` (`I : h^m` is contained
    in the saturation, and contains it once the generators are in it).
    Iterated ideal quotients cost an elimination each, one of a minute on
    an intersection of three random curves."""
    m = 0
    factor = ideal.normal_form(h)
    for g in saturated.gens:
        product = ideal.normal_form(g)
        for _ in range(m):
            product = ideal.normal_form(product*factor)
        while product.terms:
            m += 1
            product = ideal.normal_form(product*factor)
    return m


def _intersection_within(components: list[PrimaryComponent[T]], ideal: Ideal[T]) -> bool:
    """Whether the intersection of the primary ideals is contained in
    ``ideal``."""
    return _intersection([q for q, _ in components], ideal).subset(ideal)


def primary_decomposition(ideal: Ideal[T]) -> list[PrimaryComponent[T]]:
    r"""An irredundant primary decomposition of an ideal of a polynomial
    ring over the rationals, as pairs ``(Q, P)`` of a primary ideal and its
    associated prime, by decreasing dimension of the primes: the ideal is
    the intersection of the ``Q``, and the ``P`` are its associated primes,
    all different, the minimal and the embedded ones.

    The reduction of Gianni, Trager and Zacharias [GTZ]_: for a maximal
    independent set `u` of variables, the extension of `I` to `K(u)[x]`
    has dimension zero, and its contraction `I^c = I : h^\infty`, for the
    product `h \in K[u]` of the leading coefficients of a Gröbner basis for
    a block order, is the intersection of the primary components of `I`
    whose primes do not meet `K[u]`; they are the minimal primes of `I^c`,
    which has no embedded ones. With `m` such that `I : h^m = I^c`,

    .. math::

        I = I^c \cap (I + (h^m)),

    and the recursion goes on with `I + (h^m)`, a larger ideal. The
    components of `I^c` are split, instead of by a primary decomposition
    over `K(u)` (a separating linear form and the factors of its minimal
    polynomial), by separators, as Shimoyama and Yokoyama do [SY]_: the
    minimal primes `P_1, \ldots, P_r` of `I^c` are known
    (:func:`minimal_primes`), and for `s_i` in the other primes and not in
    `P_i`, `I^c : s_i^\infty` is the `P_i`-primary component. The
    components found are finally merged by prime, and those which contain
    the intersection of the others are removed.

    Examples
    ========

    The ``y`` axis with an embedded point at the origin:

    >>> from sympy_extras.core import symbols
    >>> from sympy_extras.polys.domains import QQ
    >>> from sympy_extras.polys.ideals import Ideal
    >>> from sympy_extras.polys.idealdecomposition import primary_decomposition
    >>> x, y, z = symbols('x y z')
    >>> primary_decomposition(Ideal([x**2, x*y], x, y, domain=QQ))
    [(Ideal([x], x, y), Ideal([x], x, y)), (Ideal([x**2, y], x, y), Ideal([x, y], x, y))]

    Three lines, one of them doubled:

    >>> for Q, P in primary_decomposition(Ideal([x*z, y**2*z, (x - 1)**2*y], x, y, z, domain=QQ)):
    ...     print(Q, P)
    Ideal([x**2 - 2*x + 1, z], x, y, z) Ideal([x - 1, z], x, y, z)
    Ideal([x, y], x, y, z) Ideal([x, y], x, y, z)
    Ideal([y, z], x, y, z) Ideal([y, z], x, y, z)
    """
    _require_rationals(ideal)
    if ideal.is_whole_ring():
        return []
    if not ideal.gens:
        return [(ideal, ideal)]
    found: list[PrimaryComponent[T]] = []
    current = ideal.reduced()
    # the intersection of the components found, to stop as soon as it is
    # the ideal: the steps after that one find redundant components only
    # (and a step can take minutes)
    found_so_far: Optional[Ideal[T]] = None
    while not current.is_whole_ring():
        components, contracted, h = _top_components(current)
        found.extend(components)
        if contracted == current:
            break
        found_so_far = contracted if found_so_far is None else found_so_far.intersect(contracted).reduced()
        if all(ideal.contains(g) for g in found_so_far.gens):
            break
        m = _saturation_exponent(current, contracted, h)
        power = _like(ideal, [pow(h, Integer(m))])
        current = (current + power).reduced()
    # the primes of different steps differ (those of a step contain the h
    # of the steps before it, which lies outside the primes of that step);
    # merge anyway, then drop the components which contain the
    # intersection of the others, the embedded ones (found last) first
    merged: list[PrimaryComponent[T]] = []
    for q, p in found:
        for i, (q2, p2) in enumerate(merged):
            if p == p2:
                merged[i] = (q2.intersect(q).reduced(), p2)
                break
        else:
            merged.append((q, p))
    kept = list(merged)
    for component in reversed(merged):
        others = [c for c in kept if c is not component]
        if others and _intersection_within(others, component[0]):
            kept = others
    return sorted(kept, key=lambda c: (-c[1].dimension(), str(c[1])))


def associated_primes(ideal: Ideal[T]) -> list[Ideal[T]]:
    """The associated primes of the ideal, minimal and embedded, by
    decreasing dimension: the primes of its primary decomposition.

    Examples
    ========

    >>> from sympy_extras.core import symbols
    >>> from sympy_extras.polys.domains import QQ
    >>> from sympy_extras.polys.ideals import Ideal
    >>> from sympy_extras.polys.idealdecomposition import associated_primes
    >>> x, y, z = symbols('x y z')
    >>> associated_primes(Ideal([x**2, x*y], x, y, domain=QQ))
    [Ideal([x], x, y), Ideal([x, y], x, y)]
    >>> associated_primes(Ideal([x*y, x*z, y*z], x, y, z, domain=QQ))
    [Ideal([x, y], x, y, z), Ideal([x, z], x, y, z), Ideal([y, z], x, y, z)]
    """
    return [p for _, p in primary_decomposition(ideal)]


def is_primary(ideal: Ideal[T]) -> bool:
    r"""Whether the ideal is primary: it has one minimal prime `P` and
    equals its contraction from `K(u)[x]` for a maximal independent set
    `u` (a primary ideal is the contraction of its extension to a
    localization at a multiplicative set outside `P`; conversely the
    contraction is the intersection of the primary components whose primes
    do not meet `K[u]`, all of them minimal).

    Examples
    ========

    >>> from sympy_extras.core import symbols
    >>> from sympy_extras.polys.domains import QQ
    >>> from sympy_extras.polys.ideals import Ideal
    >>> from sympy_extras.polys.idealdecomposition import is_primary
    >>> x, y, z = symbols('x y z')
    >>> is_primary(Ideal([x**2, y**3], x, y, domain=QQ)), is_primary(Ideal([x**2, x*y], x, y, domain=QQ))
    (True, False)
    >>> is_primary(Ideal([x**2, y], x, y, z, domain=QQ)), is_primary(Ideal([x*y], x, y, domain=QQ))
    (True, False)
    """
    _require_rationals(ideal)
    if ideal.is_whole_ring():
        return False
    if not ideal.gens:
        return True
    contracted, _ = _contraction(ideal, independent_set(ideal))
    return contracted == ideal and len(minimal_primes(ideal)) == 1
