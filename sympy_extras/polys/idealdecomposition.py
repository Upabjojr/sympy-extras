T = TypeVar('T')

#: a primary ideal and its associated prime
PrimaryComponent = tuple[Ideal[T], Ideal[T]]


def _like(ideal: Ideal[T], exprs: list[Expr]) -> Ideal[T]:
    """The ideal of the ring of ``ideal`` generated by core expressions."""
    return Ideal(exprs, *ideal.symbols, domain=ideal.domain, order=ideal.order)


def _whole_ring(ideal: Ideal[T]) -> Ideal[T]:
    return _like(ideal, [Integer(1)])


def _components(ideal: Ideal[T]) -> list[tuple[RegularChain, Ideal[T]]]:
    """Squarefree regular chains whose saturated ideals intersect in the
    radical of the ideal, without those which contain another one. The
    chains are those of the given generators, not of a Gröbner basis
    (whose coefficients are much larger)."""
    if not isinstance(ideal.domain, RationalField):
        raise NotImplementedError("ideals of positive dimension are decomposed over the rationals only")
    found: list[tuple[RegularChain, Ideal[T]]] = []
    for chain in triangularize(ideal.exprs, *ideal.symbols, mode='kalkbrener'):
        saturated = chain.saturated_ideal()
        found.append((chain, _like(ideal, saturated.exprs).reduced()))
    kept: list[tuple[RegularChain, Ideal[T]]] = []
    for i, (chain, saturated_i) in enumerate(found):
        redundant = False
        for j, (_, other) in enumerate(found):
            if i != j and other.subset(saturated_i) and (j < i or not saturated_i.subset(other)):
                redundant = True
                break
        if not redundant:
            kept.append((chain, saturated_i))
    return kept


def _require_rationals(ideal: Ideal[T]) -> None:
    if not isinstance(ideal.domain, RationalField):
        raise NotImplementedError("ideals are decomposed over the rationals only")


def _intersection(ideals: list[Ideal[T]], within: Ideal[T]) -> Ideal[T]:
    result = _whole_ring(within)
    first = True
    for ideal in ideals:
        result = ideal if first else result.intersect(ideal)
        first = False
    return result.reduced()


def _without(ideal: Ideal[T], other: Ideal[T]) -> Ideal[T]:
    """``ideal : other**oo``, for a radical ``ideal`` the intersection of
    its primes which do not contain ``other``: that of the saturations by
    the generators of ``other``."""
    parts = [ideal.saturate(g) for g in other.gens if not ideal.contains(g)]
    if not parts:
        return _whole_ring(ideal)
    return _intersection([part for part in parts if not part.is_whole_ring()], ideal)


def radical(ideal: Ideal[T]) -> Ideal[T]:
    """The radical of an ideal of a polynomial ring over the rationals, as
    the intersection of the saturated ideals of squarefree regular chains
    (in every dimension; :meth:`Ideal.radical
    <sympy_extras.polys.ideals.Ideal.radical>` uses Seidenberg's lemma in
    dimension zero).

    Examples
    ========

    >>> from sympy_extras.core import symbols
    >>> from sympy_extras.polys.domains import QQ
    >>> from sympy_extras.polys.ideals import Ideal
    >>> from sympy_extras.polys.idealdecomposition import radical
    >>> x, y, z = symbols('x y z')
    >>> radical(Ideal([x**2*y, x*y**2], x, y, domain=QQ))
    Ideal([x*y], x, y)
    >>> radical(Ideal([(x**2 + y**2 - z**2)**2, (x - y)**3*(x**2 + y**2 - z**2)], x, y, z, domain=QQ))
    Ideal([x**2 + y**2 - z**2], x, y, z)
    """
    if not ideal.gens:
        return ideal
    # (no Gröbner basis of the ideal itself is needed: without zeros there
    # is no chain, and the empty intersection is the whole ring)
    return _intersection([saturated for _, saturated in _components(ideal)], ideal)


def equidimensional_parts(ideal: Ideal[T]) -> list[Ideal[T]]:
    """The equidimensional parts of the radical of the ideal, by decreasing
    dimension: the part of dimension `d` is the intersection of the
    minimal primes of the ideal of dimension `d`, and the radical is the
    intersection of the parts.

    Examples
    ========

    A plane, a line and a point:

    >>> from sympy_extras.core import symbols
    >>> from sympy_extras.polys.domains import QQ
    >>> from sympy_extras.polys.ideals import Ideal
    >>> from sympy_extras.polys.idealdecomposition import equidimensional_parts
    >>> x, y, z = symbols('x y z')
    >>> equidimensional_parts(Ideal([x*z*(z - 1), x*y*(z - 1), x*(x - 1)*(z - 1)], x, y, z, domain=QQ))
    [Ideal([x*z - x], x, y, z), Ideal([x - 1, y, z], x, y, z)]
    >>> equidimensional_parts(Ideal([x*z, x*y, x*(x - 1)*(z - 1)], x, y, z, domain=QQ))
    [Ideal([x], x, y, z), Ideal([x - 1, y, z], x, y, z)]
    """
    if not ideal.gens:
        return [ideal]
    by_dimension: dict[int, list[Ideal[T]]] = {}
    for chain, saturated in _components(ideal):
        by_dimension.setdefault(chain.dimension, []).append(saturated)
    parts: list[Ideal[T]] = []
    for dimension in sorted(by_dimension, reverse=True):
        part = _intersection(by_dimension[dimension], ideal)
        for greater in parts:
            part = _without(part, greater)
        if not part.is_whole_ring():
            parts.append(part)
    return parts


def _degree_in_first(f: PolyElement[T]) -> int:
    return max((m[0] for m in f.terms), default=-1)


def _separated(chain: RegularChain, saturated: Ideal[T]) -> tuple[Expr, Expr, Symbol]:
    """A separating linear form in the main variables of the chain, and
    its minimal polynomial over the free ones, in a new variable."""
    main, free, degree = chain.main_variables, chain.free_variables, chain.degree
    y = Dummy('y')
    for form in separating_forms(main, degree):
        exprs = saturated.exprs + [add(y, mul(Integer(-1), form))]
        extended = Ideal(exprs, *main, y, *free, domain=saturated.domain, order=saturated.order)
        eliminated = extended.eliminate(main)
        eliminant = eliminated.groebner_basis()
        if len(eliminant) != 1:
            raise RuntimeError("the eliminant of an unmixed ideal is not principal")
        # the eliminated ideal lives in K[y, u]: y is its first variable
        if _degree_in_first(eliminant[0]) == degree:
            return form, eliminated.to_expr(eliminant[0]), y
    raise RuntimeError("no separating linear form was found")


def _primes(chain: RegularChain, saturated: Ideal[T]) -> list[Ideal[T]]:
    """The prime components of the saturated ideal of a squarefree chain."""
    if chain.degree == 1:
        return [saturated]
    form, minimal, y = _separated(chain, saturated)
    variables: list[Expr] = [y]
    variables.extend(chain.free_variables)
    _, found = Poly(minimal, *variables).factor_list()
    factors = [as_expr(f.as_expr().xreplace({y: form})) for f, _ in found if f.degree(y) > 0]
    if len(factors) == 1:
        return [saturated]
    primes: list[Ideal[T]] = []
    for j in range(len(factors)):
        others = mul(*[f for k, f in enumerate(factors) if k != j])
        primes.append(saturated.saturate(others).reduced())
    return primes


def minimal_primes(ideal: Ideal[T]) -> list[Ideal[T]]:
    """The minimal primes of the ideal, by decreasing dimension: the ideals
    of the irreducible components (over the rationals) of its zeros.

    Examples
    ========

    >>> from sympy_extras.core import symbols
    >>> from sympy_extras.polys.domains import QQ
    >>> from sympy_extras.polys.ideals import Ideal
    >>> from sympy_extras.polys.idealdecomposition import minimal_primes
    >>> x, y, z = symbols('x y z')
    >>> minimal_primes(Ideal([x*z - y**2, x**2 - y*z], x, y, z, domain=QQ))
    [Ideal([x - z, y - z], x, y, z), Ideal([x, y], x, y, z), Ideal([y**2 + y*z + z**2, x + y + z], x, y, z)]
    >>> minimal_primes(Ideal([x**2 - 2*y**2], x, y, domain=QQ))
    [Ideal([x**2 - 2*y**2], x, y)]
    """
    if not ideal.gens:
        return [ideal]
    candidates: list[Ideal[T]] = []
    for chain, saturated in _components(ideal):
        for prime in _primes(chain, saturated):
            if not any(prime == other for other in candidates):
                candidates.append(prime)
    minimal = [p for p in candidates if not any(q is not p and q.subset(p) for q in candidates)]
    return sorted(minimal, key=lambda p: (-p.dimension(), str(p)))


