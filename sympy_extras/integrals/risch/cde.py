"""
Algorithms for solving the Coupled Differential System.

Given a differential field k and f1, f2, g1, g2 in k, the coupled
differential system problem is to decide whether the system

    Dy1 + f1*y1 - f2*y2 == g1
    Dy2 + f2*y1 + f1*y2 == g2

has a solution (y1, y2) in k x k, and to find one if there are some.
Writing y == y1 + y2*sqrt(-1), the system is exactly the real and
imaginary parts of the Risch differential equation

    Dy + (f1 + f2*sqrt(-1))*y == g1 + g2*sqrt(-1)

over k(sqrt(-1)), where D is extended by D(sqrt(-1)) == 0.  Coupled
systems are only generated by the integration algorithm when
sqrt(-1) is not in k (they arise from the hypertangent case, Sections
5.10 and 6.6), so the equivalence goes both ways and
coupled_DE_system() solves the system through the equivalent Risch
differential equation.

For k == k0(t) with t a monomial over k0, Bronstein's Chapter 8 also
gives direct algorithms for the cancellation cases of the Risch
differential equation which recurse into coupled systems over k0
instead of Risch differential equations over k0(sqrt(-1)):
coupled_DE_cancel_prim() (Section 8.1), coupled_DE_cancel_exp()
(Section 8.2), and coupled_DE_cancel_tan() (Section 8.4); Section 8.3
(nonlinear monomials) has no general algorithm, just as in the Risch
differential equation case.

The code in this module is a specialization of Chapter 8 to
a == -1: the book states Sections 8.1 and 8.2 for a general constant
a with sqrt(a) not in k(t), but the integration algorithm only ever
generates a == -1, and the hypertangent case of Section 8.4 requires
it.

Ported from SymPy (Aaron Meurer's pull request sympy/sympy#30292, see the
notice below) on the polynomials of :mod:`sympy_extras.integrals.risch.tower`:
``sqrt(-1)`` is the generator ``I`` of the field, and the real and imaginary
parts are taken by the substitution ``I -> -I``.

Examples
========

>>> from sympy_extras.core import symbols
>>> from sympy_extras.integrals.risch.risch import DifferentialExtension
>>> from sympy_extras.integrals.risch.cde import coupled_DE_system
>>> from sympy_extras.integrals.risch.tower import TowerPoly
>>> x = symbols('x')
>>> DE = DifferentialExtension.manual([TowerPoly.from_expr(1, x)])
>>> P = lambda e: (TowerPoly.from_expr(e, x), TowerPoly.from_expr(1, x))
>>> coupled_DE_system(P(1), P(-1), P(-2*x), P(-2*(x + 1)), DE)
((TowerPoly(0, x), TowerPoly(1, x)), (TowerPoly(-2*x, x), TowerPoly(1, x)))
"""

