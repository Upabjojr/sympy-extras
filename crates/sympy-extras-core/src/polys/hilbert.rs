//! Port of `sympy_extras/polys/hilbert.py`: Hilbert series of monomial
//! ideals by Bigatti's algorithm.
//!
//! The Hilbert series of `K[x_1, ..., x_n]/M` for a monomial ideal `M` is
//! `N(t)/(1 - t)**n` with a polynomial numerator `N`, which satisfies
//! `N(M' + (m)) = N(M') - t**deg(m) N(M' : m)`. Bigatti's algorithm applies
//! this identity with a *pivot* `x_j**e` (`x_j` the variable in the most
//! generators, `e` the median of its exponents) and stops at the ideals
//! whose numerator has a formula: products of ideals in disjoint variables,
//! and pure powers with at most one more monomial.
//!
//! The Python functions return a SymPy `Poly` and an expression in a symbol
//! `t`; here the numerator is a dense polynomial over `ZZ` (highest degree
//! first, as in [`super::densebasic`]) and the series a [`HilbertSeries`].
//!
//! References
//! ==========
//!
//! 1. A. M. Bigatti, *Computation of Hilbert-Poincaré series*, Journal of
//!    Pure and Applied Algebra 119 (1997), 237-253.
//! 2. D. Cox, J. Little, D. O'Shea, *Ideals, Varieties, and Algorithms*,
//!    4th ed., Springer, 2015, Chapter 9.

use crate::numbers::*;

use super::rings::{monomial_divides, Monomial};

/// A polynomial in `t` with integer coefficients, dense, lowest degree
/// first (the internal representation of the Python module).
type Series = Vec<Int>;

/// The Hilbert series `numerator/(1 - t)**exponent`, reduced: `exponent`
/// is the Krull dimension unless the numerator is zero.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HilbertSeries {
    /// Dense over `ZZ`, highest degree first.
    pub numerator: Vec<Int>,
    pub exponent: usize,
}

fn degree(m: &[u32]) -> u64 {
    m.iter().map(|e| *e as u64).sum()
}

fn support_size(m: &[u32]) -> usize {
    m.iter().filter(|e| **e != 0).count()
}

/// The first index of a maximal value, as Python's `max(range(n), key=...)`.
fn first_argmax<T: Ord>(values: &[T]) -> usize {
    let mut best: usize = 0;
    for (i, v) in values.iter().enumerate() {
        if *v > values[best] {
            best = i;
        }
    }
    best
}

fn sort_by_degree(monomials: &mut [Monomial]) {
    monomials.sort_by(|a, b| degree(a).cmp(&degree(b)).then_with(|| a.cmp(b)));
}

/// The minimal generators of the monomial ideal generated by the exponent
/// vectors, sorted by degree.
pub fn minimal_generators(monomials: &[Monomial]) -> Vec<Monomial> {
    let mut distinct: Vec<Monomial> = monomials.to_vec();
    sort_by_degree(&mut distinct);
    distinct.dedup();
    let mut minimal: Vec<Monomial> = Vec::new();
    for m in distinct {
        if !minimal.iter().any(|u| monomial_divides(u, &m)) {
            minimal.push(m);
        }
    }
    minimal
}

/// The numerator `N(t)` of the Hilbert series `N(t)/(1 - t)**n` of
/// `K[x_1, ..., x_n]/M`, `M` generated by the exponent vectors, dense over
/// `ZZ` (highest degree first; `[]` is zero).
pub fn hilbert_numerator(monomials: &[Monomial]) -> Vec<Int> {
    let mut coefficients: Series = numerator(&minimal_generators(monomials));
    while coefficients.last().is_some_and(|c| c.is_zero()) {
        coefficients.pop();
    }
    coefficients.reverse();
    coefficients
}

/// The Hilbert series of `K[x_1, ..., x_n]/M` (`n = variables`) as a
/// reduced rational function `q(t)/(1 - t)**d`.
pub fn hilbert_series(monomials: &[Monomial], variables: usize) -> HilbertSeries {
    // lowest degree first while dividing
    let mut low: Series = hilbert_numerator(monomials);
    low.reverse();
    let mut exponent: usize = variables;
    while exponent > 0 && !low.is_empty() {
        // N = q (1 - t): q_i = a_0 + ... + a_i, the remainder N(1)
        let mut quotient: Series = Vec::with_capacity(low.len());
        let mut sum: Int = Int::ZERO;
        for a in &low {
            sum += a;
            quotient.push(sum.clone());
        }
        if !sum.is_zero() {
            break;
        }
        quotient.pop();
        low = quotient;
        exponent -= 1;
    }
    low.reverse();
    HilbertSeries {
        numerator: low,
        exponent,
    }
}

fn multiply(f: &[Int], g: &[Int]) -> Series {
    let mut result: Series = vec![Int::ZERO; f.len() + g.len() - 1];
    for (i, a) in f.iter().enumerate() {
        if !a.is_zero() {
            for (j, b) in g.iter().enumerate() {
                result[i + j] += a * b;
            }
        }
    }
    result
}

/// `f + sign * t**shift * g`.
fn add_shifted(f: &[Int], g: &[Int], shift: usize, sign: i64) -> Series {
    let mut result: Series = f.to_vec();
    if shift + g.len() > f.len() {
        result.resize(shift + g.len(), Int::ZERO);
    }
    let s: Int = Int::from(sign);
    for (j, b) in g.iter().enumerate() {
        result[shift + j] += &s * b;
    }
    result
}

/// `1 - t**a`.
fn one_minus_power(a: u64) -> Series {
    let mut result: Series = vec![Int::ZERO; a as usize + 1];
    result[0] = Int::ONE;
    result[a as usize] -= Int::ONE;
    result
}

/// The generators grouped by the connected components of the graph whose
/// edges join the generators with meeting supports: the ideal is the sum of
/// the ideals of the components, in disjoint sets of variables.
fn components(gens: &[Monomial]) -> Vec<Vec<Monomial>> {
    let n: usize = gens[0].len();
    let mut owner: Vec<usize> = (0..gens.len()).collect();
    fn find(owner: &mut [usize], mut i: usize) -> usize {
        while owner[i] != i {
            owner[i] = owner[owner[i]];
            i = owner[i];
        }
        i
    }
    for j in 0..n {
        let mut first: Option<usize> = None;
        for (i, m) in gens.iter().enumerate() {
            if m[j] != 0 {
                match first {
                    None => first = Some(find(&mut owner, i)),
                    Some(root) => {
                        let r: usize = find(&mut owner, i);
                        owner[r] = root;
                    }
                }
            }
        }
    }
    // the groups in the order of their first generator, as a Python dict
    let mut roots: Vec<usize> = Vec::new();
    let mut groups: Vec<Vec<Monomial>> = Vec::new();
    for (i, m) in gens.iter().enumerate() {
        let root: usize = find(&mut owner, i);
        match roots.iter().position(|r| *r == root) {
            Some(index) => groups[index].push(m.clone()),
            None => {
                roots.push(root);
                groups.push(vec![m.clone()]);
            }
        }
    }
    groups
}

/// Bigatti's recursion on a minimal generating set.
fn numerator(gens: &[Monomial]) -> Series {
    if gens.is_empty() {
        return vec![Int::ONE];
    }
    if gens.len() == 1 {
        if degree(&gens[0]) == 0 {
            return vec![Int::ZERO];
        }
        return one_minus_power(degree(&gens[0]));
    }
    let parts: Vec<Vec<Monomial>> = components(gens);
    if parts.len() > 1 {
        let mut result: Series = vec![Int::ONE];
        for part in &parts {
            result = multiply(&result, &numerator(part));
        }
        return result;
    }
    let pure: Vec<&Monomial> = gens.iter().filter(|m| support_size(m) == 1).collect();
    if pure.len() + 1 >= gens.len() {
        // pure powers x_i**a_i and one more monomial m:
        // prod (1 - t**a_i) - t**deg(m) prod (1 - t**(a_i - m_i))
        let others: Vec<&Monomial> = gens.iter().filter(|m| support_size(m) > 1).collect();
        // pure powers in one variable cannot both be minimal, so without
        // another monomial the generators are in disjoint variables
        assert!(!others.is_empty(), "pure powers in one component");
        let m: &Monomial = others[0];
        let mut result: Series = vec![Int::ONE];
        let mut quotient: Series = vec![Int::ONE];
        for power in &pure {
            let j: usize = first_argmax(power);
            result = multiply(&result, &one_minus_power(power[j] as u64));
            quotient = multiply(&quotient, &one_minus_power((power[j] - m[j]) as u64));
        }
        return add_shifted(&result, &quotient, degree(m) as usize, -1);
    }
    // the pivot x_j**e: x_j the variable in the most generators, e the
    // lower median of its exponents
    let n: usize = gens[0].len();
    let counts: Vec<usize> = (0..n).map(|j| gens.iter().filter(|m| m[j] != 0).count()).collect();
    let j: usize = first_argmax(&counts);
    let mut exponents: Vec<u32> = gens.iter().map(|m| m[j]).filter(|e| *e != 0).collect();
    exponents.sort();
    let e: u32 = exponents[(exponents.len() - 1) / 2];
    // M + (p): the generators not divisible by p, and p
    let pivot: Monomial = (0..n).map(|i| if i == j { e } else { 0 }).collect();
    let mut plus: Vec<Monomial> = gens.iter().filter(|m| m[j] < e).cloned().collect();
    plus.push(pivot);
    sort_by_degree(&mut plus);
    // M : p = (m / gcd(m, p))
    let colon: Vec<Monomial> = gens
        .iter()
        .map(|m| {
            m.iter()
                .enumerate()
                .map(|(i, a)| if i == j { a.saturating_sub(e) } else { *a })
                .collect()
        })
        .collect();
    let quotient_gens: Vec<Monomial> = minimal_generators(&colon);
    // N(M + (p)) = N(M) - t**e N(M : p), solved for N(M)
    add_shifted(&numerator(&plus), &numerator(&quotient_gens), e as usize, 1)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ints(v: &[i64]) -> Vec<Int> {
        v.iter().map(|c| Int::from(*c)).collect()
    }

    #[test]
    fn doctests() {
        assert_eq!(
            minimal_generators(&[vec![2, 1], vec![1, 0], vec![0, 3], vec![1, 3]]),
            vec![vec![1, 0], vec![0, 3]]
        );
        assert_eq!(hilbert_numerator(&[vec![2, 0], vec![0, 2]]), ints(&[1, 0, -2, 0, 1]));
        assert_eq!(hilbert_numerator(&[vec![1, 1, 0], vec![0, 1, 1]]), ints(&[1, -2, 0, 1]));
        assert_eq!(hilbert_numerator(&[]), ints(&[1]));
        assert_eq!(
            hilbert_series(&[vec![2, 0], vec![1, 1], vec![0, 2]], 2),
            HilbertSeries {
                numerator: ints(&[2, 1]),
                exponent: 0
            }
        );
        assert_eq!(
            hilbert_series(&[vec![2, 0, 0], vec![1, 1, 0], vec![0, 2, 0]], 3),
            HilbertSeries {
                numerator: ints(&[2, 1]),
                exponent: 1
            }
        );
        assert_eq!(
            hilbert_series(&[vec![1, 0], vec![0, 1]], 2),
            HilbertSeries {
                numerator: ints(&[1]),
                exponent: 0
            }
        );
    }
}
