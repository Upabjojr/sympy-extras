//! Port of `sympy_extras/polys/f4.py`: Gröbner bases by Faugère's F4
//! algorithm, on the sparse polynomials of [`super::rings`].
//!
//! F4 selects a set of critical pairs, writes the two halves `m_i g_i`,
//! `m_j g_j` of each S-polynomial as the rows of a sparse matrix whose
//! columns are the monomials in decreasing order, adds by *symbolic
//! preprocessing* a reducer `m g` for every monomial of the rows which is
//! not yet a leading monomial of a row, and reduces the whole matrix at once
//! to reduced row echelon form: the rows whose leading monomial is not among
//! the leading monomials of the original rows are the new basis elements.
//! The critical pairs are pruned with the criteria of Gebauer and Möller,
//! and the result is interreduced into the reduced Gröbner basis.
//!
//! For a graded order the *normal strategy* takes all the pairs whose lcm
//! has the lowest degree; for the other orders the [`SELECTION`] pairs with
//! the smallest lcms are taken.
//!
//! References
//! ==========
//!
//! 1. J.-C. Faugère, *A new efficient algorithm for computing Gröbner bases
//!    (F4)*, Journal of Pure and Applied Algebra 139 (1999), 61-88.
//! 2. R. Gebauer, H. M. Möller, *On an installation of Buchberger's
//!    algorithm*, Journal of Symbolic Computation 6 (1988), 275-286.
//! 3. T. Becker, V. Weispfenning, *Gröbner Bases*, Springer, 1993, Section
//!    5.5.

use std::collections::{BTreeMap, BTreeSet, HashSet};
use std::sync::Arc;

use crate::error::{value_error, PolyResult};

use super::domains::{Domain, SparseRow};
use super::rings::{
    monomial_div, monomial_divides, monomial_lcm, monomial_mul, Monomial, MonomialOrder, PolyElement, PolyRing,
};

/// The number of pairs selected at a time for the orders which are not
/// graded.
pub const SELECTION: usize = 16;

/// A critical pair: the indices of its two elements in the basis and the lcm
/// of their leading monomials.
type Pair = (usize, usize, Monomial);

/// A row of the matrix: the multiplier and the index of the basis element it
/// multiplies.
type Row = (Monomial, usize);

fn exact_div(a: &[u32], b: &[u32]) -> Monomial {
    monomial_div(a, b).expect("the leading monomial divides")
}

/// The reduced Gröbner basis of the ideal generated by `polys` in `ring`
/// (whose domain must be a field; `Value` otherwise) for the order of the
/// ring, sorted by decreasing leading monomial.
pub fn f4<K: Domain>(polys: &[PolyElement<K>], ring: &Arc<PolyRing<K>>) -> PolyResult<Vec<PolyElement<K>>> {
    if !ring.domain.is_field() {
        return Err(value_error(format!(
            "F4 needs a field as the coefficient domain, got {}",
            ring.domain.name()
        )));
    }
    let mut basis: Vec<PolyElement<K>> = Vec::new();
    let mut pairs: Vec<Pair> = Vec::new();
    for f in polys {
        if !f.is_zero() {
            update(&mut basis, &mut pairs, f.monic()?);
        }
    }
    let order: &MonomialOrder = &ring.order;
    let graded: bool = is_graded(ring);
    while !pairs.is_empty() {
        let selected: Vec<Pair> = select(&mut pairs, order, graded);
        let rows: Vec<Row> = symbolic_preprocessing(&selected, &basis, order);
        for h in reduce_rows(&rows, &basis, ring) {
            update(&mut basis, &mut pairs, h);
        }
    }
    Ok(reduced_basis(&basis, ring))
}

/// Whether the order of the ring compares total degrees first (every square
/// of a variable above every variable).
pub fn is_graded<K: Domain>(ring: &PolyRing<K>) -> bool {
    ring.order.is_graded(ring.ngens)
}

fn degree(m: &[u32]) -> u64 {
    m.iter().map(|e| *e as u64).sum()
}

/// The pairs to reduce together, removed from `pairs`: for a graded order
/// all the pairs whose lcm has the minimal degree, otherwise the
/// [`SELECTION`] pairs with the smallest lcms.
fn select(pairs: &mut Vec<Pair>, order: &MonomialOrder, graded: bool) -> Vec<Pair> {
    if graded {
        let lowest: u64 = pairs.iter().map(|p| degree(&p.2)).min().expect("a pair");
        let (selected, others): (Vec<Pair>, Vec<Pair>) = pairs.drain(..).partition(|p| degree(&p.2) == lowest);
        *pairs = others;
        return selected;
    }
    pairs.sort_by(|a, b| order.cmp(&a.2, &b.2));
    let rest: Vec<Pair> = if pairs.len() > SELECTION {
        pairs.split_off(SELECTION)
    } else {
        Vec::new()
    };
    std::mem::replace(pairs, rest)
}

/// The basis and the critical pairs after `h` joins the basis, with the
/// criteria of Gebauer and Möller.
fn update<K: Domain>(basis: &mut Vec<PolyElement<K>>, pairs: &mut Vec<Pair>, h: PolyElement<K>) {
    let lm_h: Monomial = h.LM();
    let index: usize = basis.len();
    let leading: Vec<Monomial> = basis.iter().map(|g| g.LM()).collect();
    let candidates: Vec<(usize, Monomial)> = (0..index).map(|i| (i, monomial_lcm(&leading[i], &lm_h))).collect();
    let mut kept: Vec<(usize, Monomial)> = Vec::new();
    for (i, lcm) in &candidates {
        if monomial_mul(&leading[*i], &lm_h) == *lcm {
            continue;
        }
        if candidates
            .iter()
            .any(|(_, other)| lcm != other && monomial_divides(other, lcm))
        {
            continue;
        }
        kept.push((*i, lcm.clone()));
    }
    let mut new: Vec<Pair> = Vec::new();
    let mut seen: HashSet<Monomial> = HashSet::new();
    for (i, lcm) in kept {
        if seen.insert(lcm.clone()) {
            new.push((i, index, lcm));
        }
    }
    pairs.retain(|(i, j, lcm)| {
        !(monomial_divides(&lm_h, lcm)
            && monomial_lcm(&leading[*i], &lm_h) != *lcm
            && monomial_lcm(&leading[*j], &lm_h) != *lcm)
    });
    pairs.extend(new);
    basis.push(h);
}

/// The rows of the matrix: the two halves of each S-polynomial and a reducer
/// for every monomial which is not a leading monomial of a row.
fn symbolic_preprocessing<K: Domain>(selected: &[Pair], basis: &[PolyElement<K>], order: &MonomialOrder) -> Vec<Row> {
    let mut rows: Vec<Row> = Vec::new();
    let mut present: HashSet<Row> = HashSet::new();
    let mut done: HashSet<Monomial> = HashSet::new();
    let leading_monomials: Vec<Monomial> = basis.iter().map(|g| g.LM()).collect();
    for (i, j, lcm) in selected {
        for k in [*i, *j] {
            let row: Row = (exact_div(lcm, &leading_monomials[k]), k);
            if present.insert(row.clone()) {
                rows.push(row);
            }
        }
        done.insert(lcm.clone());
    }
    let mut leading: Vec<(Monomial, usize)> = leading_monomials
        .iter()
        .cloned()
        .enumerate()
        .map(|(k, m)| (m, k))
        .collect();
    leading.sort_by(|a, b| order.cmp(&a.0, &b.0));
    let mut pending: Vec<Monomial> = Vec::new();
    let mut seen: HashSet<Monomial> = HashSet::new();
    for (multiplier, k) in &rows {
        for monomial in basis[*k].terms.keys() {
            let m: Monomial = monomial_mul(multiplier, monomial);
            if seen.insert(m.clone()) {
                pending.push(m);
            }
        }
    }
    while let Some(m) = pending.pop() {
        if !done.insert(m.clone()) {
            continue;
        }
        for (lm, k) in &leading {
            if monomial_divides(lm, &m) {
                let multiplier: Monomial = exact_div(&m, lm);
                let row: Row = (multiplier.clone(), *k);
                if present.insert(row.clone()) {
                    rows.push(row);
                }
                for monomial in basis[*k].terms.keys() {
                    let mm: Monomial = monomial_mul(&multiplier, monomial);
                    if seen.insert(mm.clone()) {
                        pending.push(mm);
                    }
                }
                break;
            }
        }
    }
    rows
}

/// The reduced row echelon form of a sparse matrix over the field `K`
/// ([`Domain::sparse_echelon`]: fraction-free over `QQ`).
pub fn row_echelon<K: Domain>(rows: &[SparseRow<K::Elem>], k: &K) -> Vec<SparseRow<K::Elem>> {
    k.sparse_echelon(rows)
}

/// The new basis elements from the matrix of the rows: the first row with
/// each leading monomial is the pivot of that column, the other rows are
/// reduced by the pivots, and the reduced echelon form of what remains gives
/// the polynomials with new leading monomials.
fn reduce_rows<K: Domain>(rows: &[Row], basis: &[PolyElement<K>], ring: &Arc<PolyRing<K>>) -> Vec<PolyElement<K>> {
    let k: &K = &ring.domain;
    let polys: Vec<PolyElement<K>> = rows
        .iter()
        .map(|(multiplier, i)| basis[*i].mul_monom(multiplier))
        .collect();
    let mut columns: Vec<Monomial> = polys
        .iter()
        .flat_map(|p| p.terms.keys().cloned())
        .collect::<BTreeSet<Monomial>>()
        .into_iter()
        .collect();
    columns.sort_by(|a, b| ring.order.cmp(b, a));
    let position: BTreeMap<&Monomial, usize> = columns.iter().enumerate().map(|(i, m)| (m, i)).collect();
    let mut pivots: BTreeMap<usize, SparseRow<K::Elem>> = BTreeMap::new();
    let mut pending: Vec<SparseRow<K::Elem>> = Vec::new();
    for p in &polys {
        let row: SparseRow<K::Elem> = p.terms.iter().map(|(m, c)| (position[m], c.clone())).collect();
        let lead: usize = position[&p.LM()];
        match pivots.entry(lead) {
            std::collections::btree_map::Entry::Occupied(_) => pending.push(row),
            std::collections::btree_map::Entry::Vacant(slot) => {
                let lead_value: K::Elem = row[&lead].clone();
                let normalised: SparseRow<K::Elem> = if k.is_one(&lead_value) {
                    row
                } else {
                    let inverse: K::Elem = k.invert(&lead_value).expect("a nonzero element of a field");
                    row.iter().map(|(c, v)| (*c, k.mul(v, &inverse))).collect()
                };
                slot.insert(normalised);
            }
        }
    }
    let remainder: Vec<SparseRow<K::Elem>> = k.sparse_reduce(&pending, &pivots);
    k.sparse_echelon(&remainder)
        .into_iter()
        .map(|row| ring.from_dict(row.into_iter().map(|(c, v)| (columns[c].clone(), v)).collect()))
        .collect()
}

/// The reduced Gröbner basis of a Gröbner basis: the elements whose leading
/// monomial another one divides are dropped, the others are reduced by each
/// other and made monic, sorted by decreasing leading monomial.
pub fn reduced_basis<K: Domain>(basis: &[PolyElement<K>], ring: &Arc<PolyRing<K>>) -> Vec<PolyElement<K>> {
    let order: &MonomialOrder = &ring.order;
    let mut nonzero: Vec<&PolyElement<K>> = basis.iter().filter(|g| !g.is_zero()).collect();
    nonzero.sort_by(|a, b| order.cmp(&a.LM(), &b.LM()));
    let mut minimal: Vec<PolyElement<K>> = Vec::new();
    for g in nonzero {
        let lm: Monomial = g.LM();
        if !minimal.iter().any(|h| monomial_divides(&h.LM(), &lm)) {
            minimal.push(g.clone());
        }
    }
    let mut result: Vec<PolyElement<K>> = Vec::new();
    for i in 0..minimal.len() {
        let others: Vec<PolyElement<K>> = minimal
            .iter()
            .enumerate()
            .filter(|(j, _)| *j != i)
            .map(|(_, g)| g.clone())
            .collect();
        let r: PolyElement<K> = if others.is_empty() {
            minimal[i].clone()
        } else {
            minimal[i].rem(&others).expect("a field")
        };
        result.push(r.monic().expect("a nonzero polynomial over a field"));
    }
    result.sort_by(|a, b| order.cmp(&b.LM(), &a.LM()));
    result
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::numbers::*;
    use crate::polys::domains::{GF, QQ};

    fn names(ns: &[&str]) -> Vec<String> {
        ns.iter().map(|s| s.to_string()).collect()
    }

    fn strings<K: Domain>(basis: &[PolyElement<K>]) -> Vec<String> {
        basis.iter().map(|g| g.to_string()).collect()
    }

    #[test]
    fn doctests() {
        let r = PolyRing::new(QQ, names(&["x", "y", "z"]), MonomialOrder::Grevlex).unwrap();
        let g = r.gens();
        let (x, y, z) = (&g[0], &g[1], &g[2]);
        let polys = vec![
            x.mul(x).add(&y.mul(y)).add(&z.mul(z)).sub(&r.one()),
            x.add(y).add(z),
            x.mul(y).mul(z).sub(&r.one()),
        ];
        assert_eq!(
            strings(&f4(&polys, &r).unwrap()),
            vec!["z**3 - 1/2*z - 1", "y**2 + y*z + z**2 - 1/2", "x + y + z"]
        );
        let l = PolyRing::new(QQ, names(&["x", "y"]), MonomialOrder::Lex).unwrap();
        let g = l.gens();
        let (x, y) = (&g[0], &g[1]);
        assert_eq!(
            strings(&f4(&[x.mul(x).sub(y), y.mul(y).sub(x)], &l).unwrap()),
            vec!["x - y**2", "y**4 - y"]
        );
        assert!(f4(&[], &l).unwrap().is_empty());
        assert_eq!(strings(&f4(&[x.clone(), l.from_int(3)], &l).unwrap()), vec!["1"]);
        let fr = PolyRing::new(GF(7).unwrap(), names(&["x", "y"]), MonomialOrder::Lex).unwrap();
        let g = fr.gens();
        let (x, y) = (&g[0], &g[1]);
        let three: u64 = 3;
        assert_eq!(
            strings(&f4(&[x.mul(x).sub(y), y.mul(y).mul_ground(&three).sub(x)], &fr).unwrap()),
            vec!["x + 4*y**2", "y**4 + 3*y"]
        );
        let reduced = reduced_basis(
            &[x.add(y).mul_ground(&2), y.mul(y).sub(&fr.one()), x.mul(y).add(x)],
            &fr,
        );
        assert_eq!(strings(&reduced), vec!["x + y", "y**2 + 6"]);
        assert!(is_graded(&r) && !is_graded(&l));
        let rows: Vec<SparseRow<Rat>> = vec![
            [(0, rat(2, 1)), (1, rat(4, 1))].into_iter().collect(),
            [(0, rat(1, 1)), (2, rat(1, 1))].into_iter().collect(),
        ];
        let expected: Vec<SparseRow<Rat>> = vec![
            [(0, rat(1, 1)), (2, rat(1, 1))].into_iter().collect(),
            [(1, rat(1, 1)), (2, rat(-1, 2))].into_iter().collect(),
        ];
        assert_eq!(row_echelon(&rows, &QQ), expected);
    }
}
