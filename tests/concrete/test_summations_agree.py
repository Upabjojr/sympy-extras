@pytest.mark.parametrize('kind, source, limits', CASES)
def test_agrees(kind: str, source: str, limits: list[list[str]]) -> None:
    f = parse(source)
    lims: list[tuple[Symbol, Expr, Expr]] = []
    for v, a, b in limits:
        var, lo, hi = parse(v), parse(a), parse(b)
        assert isinstance(var, Symbol) and isinstance(lo, Expr) and isinstance(hi, Expr)
        lims.append((var, lo, hi))
    if kind == 'sum':
        e = sum_(f, *lims)
        py = outcome(lambda: sum_doit(e) if isinstance(e, Sum) else e)
        rs = outcome(lambda: rc.logic_call('sum_doit', [e]))
    elif kind == 'product':
        e = product_(f, *lims)
        py = outcome(lambda: product_doit(e) if isinstance(e, Product) else e)
        rs = outcome(lambda: rc.logic_call('product_doit', [e]))
    else:
        python = deltasummation if kind == 'dsum' else deltaproduct
        op = 'deltasummation' if kind == 'dsum' else 'deltaproduct'
        py = outcome(lambda: python(f, lims[0]))
        rs = outcome(lambda: rc.logic_call(op, [f, Tuple(*lims[0])]))
    if rs == 'SKIP':
        pytest.skip('not ported')
    assert py == rs
