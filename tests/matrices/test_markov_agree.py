def outcome(f: Callable[[], object]) -> str:
    try:
        r = f()
    except NotImplementedError as e:
        return 'SKIP' if 'not ported' in str(e) else 'NotImplementedError'
    except Exception as e:
        return type(e).__name__
    return str(r)


def encoded(v: object) -> Basic:
    if isinstance(v, bool):
        return Symbol(str(v))
    if isinstance(v, ExprMatrix):
        return Tuple(Integer(v.rows), Integer(v.cols), Tuple(*v.entries))
    if isinstance(v, CommunicatingClass):
        return Tuple(Tuple(*[Integer(s) for s in v.states]), Symbol(str(v.recurrent)), Integer(v.period))
    if isinstance(v, (list, tuple)):
        return Tuple(*[encoded(x) for x in v])
    if isinstance(v, int):
        return Integer(v)
    assert isinstance(v, Basic)
    return v


def argument(a: object) -> object:
    if isinstance(a, list):
        return [argument(x) for x in a]
    if isinstance(a, int):
        return a
    return parse(str(a))


def python(name: str, P: ExprMatrix, args: list[object]) -> object:
    chain = MarkovChain(P)
    if name == 'new':
        return chain.P
    if name in PROPERTIES:
        return getattr(chain, name)
    return getattr(chain, name)(*args)


