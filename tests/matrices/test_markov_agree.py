@pytest.mark.parametrize('i', range(len(CASES)))
def test_markov(i: int) -> None:
    name, raw = CASES[i]
    matrix = raw[0]
    assert isinstance(matrix, list)
    rows, cols, entries = matrix
    assert isinstance(rows, int) and isinstance(cols, int) and isinstance(entries, list)
    P = ExprMatrix(rows, cols, [parse(str(e)) for e in entries])
    args = [argument(a) for a in raw[1:]]
