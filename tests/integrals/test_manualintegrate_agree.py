def names(r: manual.Rule) -> str:
    """The rule and its substeps as ``Name(child, ...)``."""
    kids: list[manual.Rule] = []
    for f in dataclasses.fields(r):
        v: Any = getattr(r, f.name)
        if isinstance(v, manual.Rule):
            kids.append(v)
        elif isinstance(v, tuple):
            for w in v:
                if isinstance(w, manual.Rule):
                    kids.append(w)
                elif isinstance(w, tuple) and w and isinstance(w[0], manual.Rule):
                    kids.append(w[0])
    n = type(r).__name__
    return n if not kids else '%s(%s)' % (n, ', '.join(names(k) for k in kids))


def outcome(f: Callable[[], object]) -> str:
    try:
        r = f()
    except NotImplementedError as e:
        return 'SKIP' if 'not ported' in str(e) else 'NotImplementedError'
    except Exception as e:
        return type(e).__name__
    return re.sub(r'\\b_?([a-zA-Z]+)_manual_\\d+\\b', r'\\1', str(r))


